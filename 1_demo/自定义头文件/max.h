#ifndef MAX_H
#define MAX_H

// ===== 自定义头文件:这里直接放"函数定义"(带函数体)=====
//
// 说明:头文件不只可以放"声明",也可以放"定义"。
// 用 #include "max.h" 时,预处理器会把本文件内容原样"复制"进包含它的 .c。
// 只要保证同一个 .h 只被一个 .c 包含(或只包含一次),就不会"重复定义"报错。
//
// 最上面/最下面的 #ifndef/#define/#endif 叫"头文件卫士",
// 防止同一个头文件被重复包含。

// 比较两数大小,返回较大值
int max(int a, int b) {
    return (a > b) ? a : b;
}

#endif
