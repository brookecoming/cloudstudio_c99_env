/*
 * 例 1.3：求两个整数中的较大者
 *
 * 解题思路：
 * --------
 * 这个程序演示了如何使用自定义函数来解决问题。思路是：
 * 1. 在 main 函数中读入两个整数 a 和 b
 * 2. 调用自定义函数 max(a, b) 来比较这两个数，返回其中的较大者
 * 3. 将返回的结果存放在变量 c 中，然后输出
 * 4. max 函数内部使用 if-else 语句：如果 x > y，返回 x；否则返回 y
 *
 * 关键知识点：
 * ----------
 * - 函数定义：int max(int x, int y) 定义一个接收两个整数参数的函数
 * - 形参与实参：形参是函数定义中的参数（x、y），实参是调用时传入的值（a、b）
 * - if-else 分支结构：根据条件选择不同的执行路径
 * - return 语句：函数的返回值，调用者可以接收这个值
 * - 函数调用：c = max(a, b); 将函数的返回值赋给变量 c
 *
 * 难点：
 * ----
 * - 理解形参与实参的对应关系：调用 max(a, b) 时，a 对应 x，b 对应 y
 * - 理解 return 语句的作用：不仅返回值，还会结束函数执行
 * - 理解函数调用是一个表达式，可以出现在赋值语句的右边
 * - if-else 的执行流程：条件为真执行 if 块，为假执行 else 块
 */

#include <stdio.h>

/* 自定义函数：求两个整数中的较大者 */
/* 参数：x 和 y 都是整型，函数返回值也是整型 */
int max(int x, int y)
{
    /* 在函数内部定义局部变量 z，用来存放较大的值 */
    int z;

    /* 比较 x 和 y：如果 x > y，将 x 的值赋给 z */
    if (x > y)
        z = x;
    /* 否则（x <= y），将 y 的值赋给 z */
    else
        z = y;

    /* 返回较大的值 z，这个值会传回到调用处 */
    return z;
}

/* 主函数 */
int main()
{
    /* 定义三个整型变量 */
    int a, b, c;

    /* 从键盘读入两个整数：%d 表示整数格式，&a 和 &b 是地址符号 */
    scanf("%d,%d", &a, &b);

    /* 调用 max 函数，将 a 和 b 作为实参传入，返回值存放在 c 中 */
    c = max(a, b);

    /* 输出结果 */
    printf("max=%d\n", c);

    /* 程序正常结束 */
    return 0;
}
