/*
 * 例 1.2：求两个整数之和
 *
 * 解题思路：
 * --------
 * 这是最简单的整数加法程序。思路很直接：
 * 1. 设置 3 个变量：a、b 用来存放两个整数，sum 用来存放它们的和
 * 2. 对 a、b 赋予具体的数值（123 和 456）
 * 3. 使用 "+" 运算符计算 a + b，并把结果存放到 sum 中
 * 4. 用 printf 把结果输出到屏幕
 *
 * 关键知识点：
 * ----------
 * - 变量的声明：int a, b, sum; 表示定义了三个整型变量
 * - 赋值运算符 "="：将右边的值传给左边的变量
 * - 算术运算符 "+"：进行加法运算
 * - printf 函数：用于输出格式化文本到屏幕
 * - %d 格式控制符：用来输出一个整数
 *
 * 难点：
 * ----
 * - 理解变量是内存中的"盒子"，可以存放数值
 * - 理解 "=" 是赋值而非等号，是单向的（a=b 不等于 b=a）
 * - 理解 printf 中的 \n 是换行符，使光标移到下一行
 */

#include <stdio.h>

int main()
{
    /* 声明三个整型变量 */
    int a, b, sum;

    /* 对变量 a 赋值为 123 */
    a = 123;

    /* 对变量 b 赋值为 456 */
    b = 456;

    /* 计算 a 和 b 的和，结果存放在 sum 中 */
    sum = a + b;

    /* 输出结果：%d 是整数的占位符，会被 sum 的值替换 */
    printf("sum is %d\n", sum);

    /* 返回 0 表示程序正常结束 */
    return 0;
}
