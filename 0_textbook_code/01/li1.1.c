/*
 * 例 1.1：最简单的 C 语言程序
 * 
 * 解题思路：
 * --------
 * 题目要求：在屏幕上输出一行信息 "This is a C program."
 * 
 * C 程序的基本结构包括三部分：
 * 1. 预处理指令（#include）— 引入标准库函数
 * 2. 主函数 main() — 程序执行的入口点
 * 3. 函数体 { ... } — 具体的执行语句
 * 
 * 关键点：
 * - printf() 是标准输入输出库函数，用于格式化输出
 * - \n 是转义序列，表示换行符
 * - return 0 表示程序正常执行完毕，返回状态码 0
 */

#include <stdio.h>        /* 包含标准输入输出库头文件 */

int main()                 /* 定义主函数，程序从这里开始执行 */
{                          /* 函数体开始 */
    printf("This is a C program.\n");  /* 输出指定的一行信息，\n 表示换行 */
    return 0;              /* 函数正常结束，返回 0 表示成功 */
}                          /* 函数体结束 */
