/*
 * 例 3.1：有人用温度计测量出用华氏法表示的温度（如 64°F），今要求把它转换为以摄氏法表示的温度（如 17.8°C）。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（这是全书第一个能完整跑起来的 C 程序）：
 * 华氏温度和摄氏温度之间有一个固定的换算公式，给定一个华氏温度 f，就能算出对应的摄氏温度 c。
 * 这道题的重点不在算法（算法极简单），而在于让你第一次完整走通"写一个程序、编译、运行、看结果"这条链路。
 *
 * 解题思路（对应课本图 3.1 的 N-S 盒图，三步顺序结构）：
 * ① 输入 f 的值（本例直接在程序里把 f 赋成 64.0）。
 * ② 按公式 c = (5.0/9) * (f - 32) 算出 c。
 * ③ 输出 c 的值。
 * 这三步从上到下依次执行，中间没有判断、也没有重复，就是最简单的"顺序结构"。
 *
 * 关键知识点：
 * - 顺序结构：语句从上到下一条接一条执行，是程序三种基本结构里最简单的一种。
 * - 变量定义：float f, c; 声明两个单精度浮点变量，因为温度会带小数。
 * - 赋值语句：f = 64.0; 把 64.0 这个值放进变量 f。
 * - 浮点常量与除法：公式里的 5/9 必须写成 5.0/9，否则会被当成整数除法算成 0（这是本题最大的坑）。
 * - printf 输出：用 %f 打印浮点数，默认保留 6 位小数；\n 表示换行。
 *
 * 难点：
 * - 理解"同一个数字，写成 5 和写成 5.0，在 C 里命运完全不同"：5 是整数、5.0 是小数，两者参与除法的结果不一样。
 * - 理解顺序程序"数据从哪来、怎么算、到哪去"：f 来自赋值，经公式变成 c，最后由 printf 送到屏幕。
 *
 * 易错易混点：
 * - 把 5.0/9 写成 5/9：整数除法 5/9 的商是 0，于是 c 恒等于 0，程序算错却不报错，最难查。
 * - 忘记给 f 赋值就直接用：f 没有初值时里面是垃圾值，算出的 c 也不对。
 * - 以为 %f 会原样显示 17.8：其实 %f 固定输出 6 位小数；且 c 是 float，本机实测打印为 17.777779（末位受单精度舍入影响，见文末运行结果说明）。
 * - 公式 (f-32) 的括号不能丢：丢了就变成 5.0/9*f-32，运算顺序全错。
 *
 * 内存与编译器原理：
 * - float 一般占 4 个字节，f = 64.0 会把 64.0 按浮点格式存进 f 的那 4 个字节。
 * - 5.0/9 因为出现小数，编译器按浮点除法计算，结果约为 0.5556；而 5/9 会按整数除法直接得 0。
 * - printf 里的 %f 是个"占位符"，运行时会把对应变量的值按浮点格式替换进去再输出。
 */

#include <stdio.h>            /* 引入标准输入输出库，提供 printf 函数 */

int main()                    /* 主函数，程序从这里开始执行 */
{
    float f, c;               /* 定义 f 和 c 为单精度浮点型变量 */
    f = 64.0;                 /* 指定 f 的值（华氏温度 64） */
    c = (5.0 / 9) * (f - 32); /* 利用公式计算 c 的值，注意 5.0/9 是浮点除法 */
    printf("f=%f\n c=%f\n", f, c);   /* 输出 f 和 c 的值，%f 各占一位、\n 换行 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC）：
 * f=64.000000
 *  c=17.777779
 *
 * 【为什么本机打印 17.777779、而课本印的是 17.777778？】
 * 真值 160/9 = 17.777777…，但 c 是 float（单精度，只有 6~7 位有效数字），
 * 存进 float 后最接近的可表示值约是 17.7777786，用 %f 保留 6 位小数就四舍五入成 17.777779；
 * 课本（多用 VC6 等老编译器）得到 17.777778。两者都"对"，只是 float 舍入 + 不同编译器实现的差异，
 * 不是代码写错。想更贴近真值可把 c 定义为 double。这里如实记录本机实测值。
 *
 * 【运行与演示】本例不需要键盘输入，f 的值直接写在程序里（f=64.0）。
 * 点 ▶ 运行即可看到输出；想换温度就改 f 那一行的数值，比如改成 100.0 再看 c 变成多少。
 */

/*
 * 【讲解过程稿】（本稿骨架照搬课本例 3.1 自己的小标题：解题思路 → 编写程序 → 运行结果 → 程序分析）
 *
 * 开场：这是全书第一个能从头跑到尾、不拐弯的完整 C 程序——把华氏温度换算成摄氏温度。【互动停顿：问一句“64 度华氏，大概多少摄氏，心里有没有个数？”停 2~3 秒再往下】
 * 解题思路（对应课本“解题思路”＋图 3.1 的 N-S 盒图）：课本一句话点破要害——这题算法很简单，关键在于找到两者间的转换公式 c = 5/9×(f−32)，f 是华氏、c 是摄氏。公式是数学语言，C 不认分数线，所以把它拆成一步一步：输入 f 的值、按公式算出 c、输出 c。右下角那张 N-S 图就是这三步——三个黑框从上排到下。回想第 2 章说的三种基本结构：顺序、选择、循环；这题里没有判断框、也没有循环框，就是最老实的顺序结构：一条道走到底，绝不回头。
 * 编写程序（对应课本“编写程序”：有了 N-S 图，逐行翻成 C 就行）：
 *   - float f, c; 定义两个浮点变量，因为温度会带小数，得用 float 不能用 int。
 *   - f = 64.0; 先把华氏温度赋成 64，注意写 64.0 而不是 64，让它按小数来存。
 *   - c = (5.0/9)*(f-32); 套公式算 c，这一步里 5.0/9 是全程序的命门，下面单独说。
 *   - printf("f=%f\nc=%f\n", f, c); 把 f 和 c 都打出来，%f 自动显示 6 位小数。
 * 运行结果（对应课本“运行结果”）：跑一遍，屏幕出 f=64.000000、c=17.777779，跟手算的约 17.8 对得上，64 华氏确实换成二十来度摄氏。
 * 程序分析（对应课本“程序分析”，本例最该强调的一处）：最容易翻车的就是那个 5.0/9。要是图省事写成 5/9，C 会先做整数除法，5 除以 9 商是 0，整个 c 就被算成 0——程序不报错，但结果是错的，这种 bug 最难查。写成 5.0/9 才是浮点除法，约等于 0.5556。顺带留个尾巴：本机打印 17.777779、课本印 17.777778，末位那点差是 float 单精度舍入加不同编译器实现的差异，不是代码写错，等学到浮点型那节会讲透。
 * 收尾：所以这个程序教会两件事——顺序结构怎么写、以及别让整数除法骗了。留个问题：如果把 f=64.0 改成 f=64，结果会变吗？【互动停顿：留几秒让大家猜，当堂揭晓“64 会自动转成 64.0 存进 float，结果不变”】
 */

