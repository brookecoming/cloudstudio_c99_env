/*
 * 例 3.8：先后输出 BOY 三个字符。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（§3.5.5 字符输入输出函数 · putchar）：
 * 除了 printf/scanf，C 函数库还提供了专门输出单个字符的函数 putchar。
 * putchar 是 "put character"（给字符）的缩写，见名知义：putchar(c) 输出字符 c，显然输出的是一个字符。
 * 本例定义 3 个字符变量 a、b、c，分别赋 'B'、'O'、'Y'，再用 putchar 逐个输出。
 *
 * 解题思路（顺序结构）：
 * ① 定义 3 个字符变量并初始化：a='B'、b='O'、c='Y'。
 * ② putchar(a) 输出 B。
 * ③ putchar(b) 输出 O。
 * ④ putchar(c) 输出 Y。
 * ⑤ putchar('\n') 输出一个换行符，光标移到下一行行首。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - putchar(c) 向显示器输出【一个字符】，三次调用连排就得到 BOY（中间不换行）。
 * - putchar 既能输出可显示字符，也能输出【控制字符】：putchar('\n') 输出换行符，使当前位置移到下一行开头。
 * - 字符型也属于整数类型：把定义改成 int a=66,b=79,c=89（其他不变）结果仍是 BOY，因为 66/79/89 正是 'B'/'O'/'Y' 的 ASCII 码，putchar 按字符输出它们（整型数据范围 0~127）。
 * - 说明：putchar(c) 的 c 可以是字符常量、整型常量、字符变量或整型变量（其值须在字符 ASCII 码范围内）；但它输出的是字符而非整数本身。
 * - putchar 可输出【转义字符】：putchar('\101') 输出 A（八进制 101=十进制 65='A'）、putchar('\'') 输出单撇号、putchar('\015') 输出回车符（八进制 15=十进制 13，光标回到本行开头、不换行）。
 *
 * 难点：
 * - 理解"字符与整数一体两面"：putchar(66) 之所以打印 B，是因为内存里字符就是 ASCII 整数。
 * - 理解 putchar 与 printf("%c") 都能输出字符，但 putchar 一次只输出一个、更简洁。
 *
 * 易错易混点：
 * - putchar 一次只能输出【一个】字符，putchar(a,b) 是错的；要输出多个就多次调用。
 * - 想输出整数 66 本身要用 printf("%d",66)，putchar(66) 输出的是字符 B 而非 "66"。
 * - 'B' 带单引号是字符常量；写成 "B" 是字符串，不能直接给 putchar。
 * - 三个字符之间没有空格，是因为 putchar 只输出字符本身、不自动加空格或换行。
 *
 * 内存与编译器原理：
 * - char 占 1 字节，存的是 ASCII 码：'B'=66、'O'=79、'Y'=89。
 * - putchar 把参数的低 8 位按 ASCII 表还原成对应字符送到标准输出。
 * - '\n' 是转义字符，编译时翻译成一个换行控制码（ASCII 10）。
 * - 输出用英文/ASCII（BOY 本就是 ASCII 字母），跨平台不乱码。
 */

#include <stdio.h>                    /* 包含标准输入输出库，提供 putchar */

int main()                            /* 定义主函数 */
{
    char a = 'B', b = 'O', c = 'Y';   /* 定义 3 个字符变量并初始化 */
    putchar(a);                       /* 向显示器输出字符 B */
    putchar(b);                       /* 向显示器输出字符 O */
    putchar(c);                       /* 向显示器输出字符 Y */
    putchar('\n');                    /* 向显示器输出一个换行符 */
    return 0;                         /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * BOY
 * 连续输出 B、O、Y 三个字符（它们之间没有空格，因为 putchar 不自动加分隔），然后换行，与课本一致。
 *
 * 【运行与演示】本例不需要键盘输入，点 ▶ 运行即可看到 BOY。
 * 动手试：把定义行改成 int a=66,b=79,c=89;（其他不变）再运行，结果仍是 BOY——字符型也属整数类型，66/79/89 就是 B/O/Y 的 ASCII 码。
 * 再试输出转义/控制字符：putchar('\101'); 输出 A（八进制 101=65）；putchar('\015'); 输出回车符（八进制 15=十进制 13），光标回到本行开头但不换行。
 */

/*
 * 【讲解过程稿】（本稿骨架照搬课本例 3.8 自己的小标题：解题思路 → 编写程序 → 运行结果 → 说明）
 *
 * 开场：前面输出都靠 printf，这题认识一个更专一的函数——它一次只干一件事：往屏幕上放一个字符，名字叫 putchar。【互动停顿：问“从名字猜，put 和 character 合起来是干什么？”停 2~3 秒】
 * 解题思路（对应课本“解题思路”）：课本点破——要输出 B、O、Y 三个字符，就用三个 putchar 函数，一个一个分别输出，最后再输出一个换行符。没有公式、没有分支，就是把“输出一个字符”这个动作重复三遍。
 * 编写程序（对应课本“编写程序”）：
 *   - char a='B',b='O',c='Y'; 一行定义并初始化三个字符变量。
 *   - putchar(a); putchar(b); putchar(c); 挨个输出，因为 putchar 不自动加空格，屏幕上紧挨着就是 BOY。
 *   - putchar('\n'); 输出一个换行控制字符，光标跳到下一行开头。
 * 运行结果（对应课本“运行结果”）：屏幕上一行 BOY，然后换行。
 * 说明（对应课本“说明”，本例最该强调的一处）：最该点破的是“putchar 眼里只有字符”——课本把变量换成 int a=66,b=79,c=89 照样输出 BOY，因为字符本质就是 ASCII 整数；你给它 66，它查表打出 B，而不是打印数字 66，想打数字得用 printf("%d")。另外 putchar 既能输出可显示字符，也能输出像 '\n' 这样的控制字符。
 * 收尾：这题让我们记住 putchar 一次出一个字符、能出控制字符、参数可以是字符或整型。留个问题：我写 putchar('\101')，屏幕会出什么？【互动停顿：留几秒，再揭晓“出字母 A——\101 是八进制 101，等于十进制 65，正是 A 的 ASCII 码”】
 */

