/*
 * 例 3.7：float 型数据的有效位数。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（§3.7 格式输出的收尾例，用 float 精度"露馅"讲透有效数字）：
 * a=10000/3.0，理论值应为 3333.33333333…（无限循环）。但 float 只能保证 6~7 位有效数字，
 * 所以虽然 %f 打了 6 位小数，从左数第 7 位有效数字（即第 3 位小数）以后的数字并不保证绝对正确。
 *
 * 解题思路（顺序结构）：
 * ① 定义单精度变量 a（float）。
 * ② a = 10000/3.0（3.0 是 double，故为浮点除法，结果约 3333.3333…存入 float）。
 * ③ 用 %f 输出 a，观察小数位虽多、但可靠精度只有 6~7 位。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - float 有效数字约 6~7 位；double 约 15~16 位。课本建议：把 a 改成 double、其他不变，上机对比结果。
 * - %f 默认输出 6 位小数，但"输出的位数"不等于"数据真实的有效位数"。
 * - 10000/3.0 是浮点除法（因 3.0 带小数点）；若写成 10000/3 则是整数除法，得 3333。
 *
 * 【本节配套知识点：printf 其余格式符（对应课本 §3.7）】
 * ③ 左对齐用 %-m.nf：在 m、n 前加负号。数据长度不超过 m 时，%m.nf 右对齐(左补空格)、%-m.nf 左对齐(右补空格)。
 *    如 printf("%-25.15f,%25.15f\n",a,a); 第 1 个左端对齐、右空 5 列，第 2 个右端对齐、左空 5 列。
 * (5) e 格式符 %e：以指数形式输出实数。不指定宽度/小数位时，许多系统(如 VC++)自动给 6 位小数、指数占 5 列。
 *    数值按规范化指数输出（小数点前必须有且只有 1 位非零数字）：printf("%e",123.456); 输出 1.234560e+002（共 13 列）。
 *    也可用 %m.ne 指定：printf("%13.2e",123.456); 输出 1.23e+002（数前 4 个空格）。e 可写大写 E，指数用 E 表示（1.23E+002）。
 * (6) 其他格式符：
 *    ① %i：与 %d 相同，按十进制整型实际长度输出，一般习惯用 %d 而少用 %i。
 *    ② %o：以八进制整数形式输出，把内存单元里实际的位值(0/1)按 3 位一组转成八进制，因此不带符号（符号位也算进八进制）。
 *       如 int a=-1; printf("%d\n%o\n",a,a); 输出 -1 和 37777777777（-1 补码全 1，转八进制即全 7）。
 *    ③ %x：以十六进制整数形式输出。printf("%d\n%o\n%x\n",a,a,a); 中 a=-1 输出 ffffffff（-1 补码全 1，每 4 位一组转十六进制即全 f）。可用 %lx、可指定宽度如 %12x。
 *    ④ %u：输出无符号(unsigned)型数据，以十进制整数形式。
 *    ⑤ %g：输出浮点数，系统自动在 f 格式和 e 格式中选长度较短者，且不输出无意义的 0。
 *       如 double a=12345678954321; printf("%f\t%e\t%g\n",a,a,a);：%f 占 21 列、%e 占 13 列，故 %g 采用 %e 形式。
 * 格式声明一般形式：% [附加字符] 格式字符。常用汇总：
 *    表 3.6 格式字符：d,i(带符号十进制整数) o(八进制无符号) x,X(十六进制无符号) u(无符号十进制) c(字符) s(字符串)
 *                     f(小数,默认6位) e,E(指数) g,G(f/e 中取较短者)。
 *    表 3.7 附加字符：l(长整型,加在 d,o,x,u 前)  m(数据最小宽度)  n(实数输出 n 位小数/字符串截取字符数)  -(域内左靠)。
 * 两条重要提醒：
 *    - 除 X、E、G 外，格式字符必须小写（%d 不能写成 %D）。
 *    - 想输出一个百分号本身，用连续两个 %% ：printf("%%%f%%\n",1.0/3); 输出 0.333333%。
 *
 * 难点：
 * - 理解"有效数字"与"小数位数"是两回事：3333.333333 共 10 位数字，但 float 只有前 6~7 位可靠，后面是凑出来的。
 * - 理解 %o/%x 打印的是内存里的补码位值，所以负数会打出一串很大的八/十六进制数。
 *
 * 易错易混点：
 * - 误以为 %f 打了 6 位小数就代表 float 有 6 位小数精度：整数部分占了 4 位(3333)，留给小数的可靠位数就很少。
 * - 想要更准的结果应把类型改成 double，而不是加大输出的小数位数（位数再多也是凑数）。
 * - 左对齐是 %-m.nf（负号在最前），别写成 %m.-nf。
 * - 用 %o 输出负数别以为是 bug——它输出的是补码按八进制的真实存储。
 *
 * 内存与编译器原理：
 * - float 占 4 字节（约 24 位尾数），对应十进制约 6~7 位有效数字。
 * - 10000/3.0 先按 double 计算，再赋给 float a 时被舍入成最接近的可表示单精度值。
 * - printf("%f") 把这个单精度值按十进制、6 位小数格式化输出，凑不出的低位就显出舍入误差。
 * - 输出用英文/ASCII（数字、e+002 本就 ASCII），跨平台不乱码。
 */

#include <stdio.h>            /* 包含标准输入输出库，提供 printf */

int main()                    /* 定义主函数 */
{
    float a;                  /* 定义单精度浮点变量 a */
    a = 10000 / 3.0;          /* 3.0 为 double，浮点除法，结果约 3333.3333… 存入 float */
    printf("%f\n", a);        /* 用 %f 输出，默认 6 位小数 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * 3333.333252
 *
 * 【实测与课本不同，而这恰恰是本例想讲的道理】理论值 3333.33333333…，课本(多用 VC++6.0)印 3333.333333，
 * 本机 GCC 打 3333.333252——两者从第 7 位有效数字起就分道扬镳（3333.333|333 与 3333.333|252）。
 * 代码与课本一字不差，这不是错误，而正是"float 只能保证 6~7 位有效数字"的活证据：a 是 float，
 * 存不下那么多位，第 7 位以后本就不可靠，不同编译器/平台舍入不同就会露馅。想稳定多几位，应把 a 改成 double。
 *
 * 【运行与演示】本例不需要键盘输入，点 ▶ 运行即可。
 * 动手实验：把第 4 行 float a; 改成 double a;（其他不变）再运行，对比精度差异；
 * 也可试 printf("%-25.15f,%25.15f\n",a,a); 看左/右对齐，printf("%e\n",a) 看指数输出，
 * printf("%%%f%%\n",1.0/3); 看如何打印出百分号本身。
 */

/*
 * 【讲解过程稿】（本例是验证型：课本一句题干直接上代码，没有“解题思路”，本稿也照此从“编写程序”讲起）
 *
 * 开场：上一题说 %f 默认打 6 位小数，那这 6 位是不是都准？这题故意用精度最差的 float 去算一个除不尽的数，让它当场露馅。【互动停顿：问“10000 除以 3，你们觉得程序能打出一串几个 3？”停 2~3 秒】
 * 编写程序（课本一句“float 型数据的有效位数”，直接给代码）：
 *   - float a; 单精度，只占 4 字节、约 6~7 位有效数字，这是全场主角。
 *   - a=10000/3.0; 注意除数写 3.0，是浮点除法；要是写 10000/3 就成了整数除法得 3333。
 *   - printf("%f\n",a); 用 %f 打出来。
 * 运行结果（观察现象是本页核心）：屏幕上出的是 3333.333252——整数部分 3333 没错，可小数最后几位不是 333 而是 252，露馅了。
 * 说明（点破为什么出这个结果）：最该点破的是“输出的位数≠有效的位数”。整数 3333 已经吃掉 4 位有效数字，float 满打满算 6~7 位，留给小数的可靠位就那么点，第 7 位以后是编译器凑出来的，换个编译器就不一样——这正说明别迷信计算机绝对精确。
 * 收尾：这题用一次露馅讲清了 float 的精度天花板。留个问题：我把 float a 改成 double a，结果会不会更准？能准到几位？【互动停顿：留几秒，再揭晓“double 约 15 位有效数字，会稳定打出 3333.3333333333335 左右，前 15 位可靠”】
 */

