/*
 * 例 3.10：改写例 3.3 程序，使之适用于任何大写字母。从键盘输入一个大写字母，在显示屏上显示对应的小写字母。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬主程序，只补充便于理解的中文注释】
 *
 * 题目背景（比例 3.3 的进步：固定数据 → 键盘输入）：
 * 例 3.3 把大写固定为 'A'（c1='A'）来演示转换原理；本例改成"从键盘读入任意大写字母"。
 * 用 getchar 取一个字符给 c1，再按"小写 = 大写 + 32"算出 c2 输出，程序就对任何大写字母都适用了。
 *
 * 解题思路（顺序结构）：
 * ① 定义两个字符变量 c1、c2。
 * ② c1 = getchar() 从键盘读入一个大写字母，赋给 c1。
 * ③ c2 = c1 + 32 求对应小写字母的 ASCII 码，放在 c2 中。
 * ④ putchar(c2) 输出 c2 的值（一个小写字母字符）。
 * ⑤ putchar('\n') 输出换行。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - 大小写转换规律：同一字母 小写 ASCII = 大写 ASCII + 32（'A'=65 → 'a'=97）。
 * - c1 + 32 用的是 c1 里字符的 ASCII 码参与整数加法，结果再当字符输出。
 * - getchar 读入一个字符、putchar 输出一个字符（承接例 3.8、3.9）。
 * - 与例 3.3 对比：把"赋值 c1='A'"换成"输入 c1=getchar()"，程序从特例变通用。
 *
 * 难点：
 * - 理解"字符参与算术运算"：c1+32 不是把字形变化，而是把 ASCII 码值加 32。
 * - 理解"输入 → 计算 → 输出"三步顺序结构里，数据从键盘来、经公式变换、再回到屏幕。
 *
 * 易错易混点：
 * - +32 记反：大写转小写是 +32，小写转大写是 -32。
 * - 只对 A~Z 的大写成立；若输入的不是大写字母，结果无意义（课本未做校验）。
 * - c2 = c1 + 32 中 c1 是 char，加法按 int 算，赋回 char 的 c2（值在 0~127 内安全）。
 * - printf 里别放中文字符串：源文件 UTF-8、Windows 控制台默认 GBK，打印中文会乱码。课本 printf 变体用了"大写字母："等中文，本文件改用英文（见文末）。
 *
 * 内存与编译器原理：
 * - getchar 从键盘缓冲区取一个字符的 ASCII 码存入 c1（1 字节）。
 * - c1 + 32 时 char 提升为 int 相加，得小写的 ASCII 码，存回 char 型 c2。
 * - putchar(c2) 把 c2 的字节按 ASCII 还原成小写字母输出。
 * - 输出用英文/ASCII（b 本就是 ASCII 字母），跨平台不乱码。
 */

#include <stdio.h>            /* 包含标准输入输出库，提供 getchar、putchar */

int main()                    /* 定义主函数 */
{
    char c1, c2;              /* 定义两个字符变量 */
    c1 = getchar();           /* 从键盘读入一个大写字母，赋给字符变量 c1 */
    c2 = c1 + 32;             /* 求对应小写字母的 ASCII 码，放在字符变量 c2 中 */
    putchar(c2);              /* 输出 c2 的值，是一个（小写）字符 */
    putchar('\n');            /* 输出一个换行符 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测，键入 B 后回车）：
 * B        <- 键入大写字母并回显
 * b        <- 程序输出的对应小写
 * 与课本一致：从键盘输入一个大写字母，在显示屏上显示对应的小写字母。
 *
 * 【运行与演示】本例用 getchar 读键盘，点 ▶ 后输入一个大写字母（如 B）再按回车，程序输出对应小写 b。
 * 想换字母直接改输入即可（H → h、N → n）。
 *
 * 【课本的 printf 变体】课本说"最后两个 putchar 可改用一个 printf 代替"，原书写作：
 *     printf("大写字母：%c\n小写字母：%c\n", c1, c2);
 * 但在 Windows(GBK) 控制台里，printf 字符串中的中文会乱码（源文件是 UTF-8）。
 * 按本项目红线（printf 输出一律英文/ASCII），等价写法应改为：
 *     printf("Upper=%c\nLower=%c\n", c1, c2);   // 输入 N → 输出 Upper=N / Lower=n
 * （课本"说明"栏也提到：只有在汉化的 C 编译系统如 VC++ 中文版里，printf 才能显示汉字；
 *  我们用的 MinGW-GCC + Windows 控制台不属此列，故用英文，避免乱码。）
 *
 * 【思考·课本原问】printf/scanf 与 putchar/getchar 各有特点：后者专用于单个字符、更简洁；
 * 前者可一次格式化输出多个数据、可加提示文字。特定场景下择优使用。
 */

