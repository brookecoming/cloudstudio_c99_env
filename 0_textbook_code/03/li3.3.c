/*
 * 例 3.3：给定一个大写字母，要求用小写字母输出。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（把"字符其实是整数"这件事第一次讲透）：
 * 字符数据在内存里存的是 ASCII 码，存放形式和整数完全相同，所以字符型数据能和其他算术类型互相赋值、运算。
 * 同一个字母，小写的 ASCII 码比大写大 32（'a'=97、'A'=65），于是"大写转小写"就是"给 ASCII 码加 32"。
 * 本题还顺手演示一件重要的事：同一个数据，既能按字符输出（%c），也能按整数输出（%d）。
 *
 * 解题思路：
 * ① 定义两个字符变量 c1、c2。
 * ② 把大写字母 'A' 放进 c1（实际存的是它的 ASCII 码 65）。
 * ③ c2 = c1 + 32，得到小写 'a' 的 ASCII 码 97，放进 c2。
 * ④ 用 %c 输出 c2，屏幕上显示字符 a。
 * ⑤ 用 %d 输出 c2，屏幕上显示整数 97。
 *
 * 关键知识点（含 §3.3.5 不同类型数据间的混合运算）：
 * - 字符以 ASCII 码存储，大小写相差 32：'A'=65、'a'=97，大写转小写就是 +32。
 * - %c 与 %d 是同一份数据的两种"看脸"方式：%c 把值当字符显示，%d 把值当十进制整数显示。
 * - 混合运算规则(1)：+ - * / 两侧只要有一个是 float 或 double，结果就是 double（系统先把各数都转成 double 再算）。
 * - 混合运算规则(2)：int 与 float/double 运算时，先把 int 转成 double，结果 double。
 * - 混合运算规则(3)：char 与整型运算，是用它的 ASCII 码参与，结果是整型；char 与实型运算，则把 ASCII 码转成 double 再算。这些转换由编译系统自动完成，用户不必过问。
 * - 本题 c2 = c1 + 32 正是"char 与整型混合运算"：c1 取 ASCII 65，加 32 得 97，再存回 char 型 c2。
 *
 * 难点：
 * - 真正转不过弯的是"字符和整数是一回事"：c1='A' 内存里放的是 65，加 32 得 97，97 又能被 %c 翻译成字母 a。
 * - 混合运算里"谁转成谁"要记牢：向精度高的方向转（int→double、char→整型参与），不是反过来。
 *
 * 易错易混点：
 * - 记反方向：大写转小写是 +32，小写转大写才是 -32。
 * - 以为 %c 和 %d 输出一样：对同一个 c2，%c 出 a、%d 出 97，别混。
 * - 混合运算误以为整数优先：只要有一个操作数是 double，整个结果就是 double，不是整数。
 * - 用 int 存字符虽然也行，但语义不如 char 清楚；课本这里用 char 是为了强调"这是字符"。
 *
 * 内存与编译器原理（对应课本图 3.13）：
 * - c2 的存储单元里放的是 97，二进制是 0110 0001，这就是字符 'a' 的 ASCII 码。
 * - 同一个 97，走 %c 格式时被翻译成字符 a 显示，走 %d 格式时按十进制整数 97 显示（见图 3.13）。
 * - 混合运算时的类型转换（char→int、int→double）由编译系统在运算前自动插入，源码里看不到但确实发生了。
 * - 输出用英文/ASCII（a、97 本就是 ASCII），跨平台不乱码。
 */

#include <stdio.h>            /* 引入标准输入输出库，提供 printf 函数 */

int main()                    /* 主函数，程序从这里开始执行 */
{
    char c1, c2;              /* 定义两个字符变量 */
    c1 = 'A';                 /* 将字符 'A' 的 ASCII 码（65）放到 c1 变量中 */
    c2 = c1 + 32;             /* 得到字符 'a' 的 ASCII 码（97），放在 c2 变量中 */
    printf("%c\n", c2);       /* 以字符形式输出 c2 的值，显示 a */
    printf("%d\n", c2);       /* 以十进制整数形式输出 c2 的值，显示 97 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * a
 * 97
 * 与课本 P76 完全一致：第一行 %c 输出字符 a，第二行 %d 输出 ASCII 码 97。
 *
 * 【运行与演示】本例不需要键盘输入，大写值直接写在程序里（c1='A'）。
 * 想换字母改 c1 即可（如 'B' → b/98）；把 c2=c1+32 改成 c2=c1-32 试试小写转大写会怎样。
 */

