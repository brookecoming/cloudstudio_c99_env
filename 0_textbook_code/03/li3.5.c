/*
 * 例 3.5：求 ax^2+bx+c=0 方程的根。a、b、c 由键盘输入，设 b^2-4ac>0。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（全书第一个要"从键盘输入数据"的程序，§3.5 数据的输入输出开篇）：
 * 一元二次方程 ax^2+bx+c=0，当判别式 b^2-4ac>=0 时有两个实根：x1=(-b+sqrt(b^2-4ac))/(2a)、x2=(-b-sqrt(b^2-4ac))/(2a)。
 * 教材把分式拆成两项以减少重复计算：p=-b/(2a)、q=sqrt(b^2-4ac)/(2a)，于是 x1=p+q、x2=p-q。
 * 本例假定输入的 a、b、c 满足 b^2-4ac>0，故程序不判断判别式正负。
 *
 * 解题思路（顺序结构，含输入与输出）：
 * ① 定义 double 型 a,b,c,disc,x1,x2,p,q。
 * ② 用 scanf 从键盘输入 a、b、c（这是课本明确要求的输入步骤）。
 * ③ 计算判别式 disc = b*b - 4*a*c。
 * ④ 计算 p = -b/(2.0*a)、q = sqrt(disc)/(2.0*a)。
 * ⑤ 计算 x1 = p+q、x2 = p-q。
 * ⑥ 用 printf 以 %7.2f 格式输出两个根。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - scanf 输入变量前要加取地址符 &：&a、&b、&c。&a 表示变量 a 在内存中的地址；scanf 把从终端读到的数据按这些地址送进 a、b、c 的存储单元。
 * - 输入 double 必须用格式声明 %lf（不是 %f！），本例连续 3 个 %lf。
 * - 运行时输入 3 个数用空格分隔（如 1 3 2），最后按回车；用逗号等其他符号会出错。
 * - 输入虽写的是整数 1、3、2，但因指定 %lf，系统会先把它们转成实数 1.0、3.0、2.0 再赋给 double 变量。
 * - printf 用 %7.2f 而非简单 %f：指定输出占 7 列、其中小数 2 位（第 3 位四舍五入）。好处一是按需保留小数位，二是多行用同一格式时，即使整数部分位数不同也能按小数点对齐，整齐美观。
 * - sqrt 属数学函数库，需 #include <math.h>。
 *
 * 【本节配套知识点：输入输出的概念（对应课本 §3.5.2）】
 * - 输入输出以"计算机主机"为主体（见图 3.17）：从计算机向输出设备（显示器、打印机）送出数据叫输出；从输入设备（键盘、光盘、扫描仪）向计算机输入数据叫输入。
 * - C 语言本身不提供输入输出语句。输入输出是由 C 标准函数库中的函数（printf、scanf 等）实现的。printf、scanf 不是 C 的关键字，只是库函数的名字，千万别误当成"输入输出语句"。
 * - 常用标准输入输出函数：putchar（输出字符）、getchar（输入字符）、printf（格式输出）、scanf（格式输入）、puts（输出字符串）、gets（输入字符串）。
 * - 要在程序开头用预处理指令 #include 把有关头文件放进本程序。用标准 IO 函数就要 #include <stdio.h>，用数学函数就要 #include <math.h>。
 * - #include 有两种形式：尖括号 #include <stdio.h> 是"标准方式"，从系统存放头文件的子目录找；双撇号 #include "stdio.h" 先在用户当前目录找，找不到再按标准方式找。用系统头文件宜用尖括号，用自己写的头文件用双撇号。
 *
 * 难点：
 * - 理解 &（取地址）：scanf 要把读到的值"放进"变量，所以必须告诉它变量的地址。
 * - 理解 %lf 与 %f 的分工：scanf 读 double 用 %lf，printf 输出 double 用 %f 即可，这一不对称最容易混。
 * - 理解求根公式到 C 表达式的翻译：分母 2a 写成 2.0*a，用小数点确保做浮点除法。
 *
 * 易错易混点：
 * - scanf 里忘加 &（写成 scanf("%lf",a)）是高频错误，会崩溃或读不到值。
 * - scanf 读 double 误用 %f：应写 %lf，否则按 float 解释、结果错乱。
 * - 输入用逗号分隔（如 1,3,2）会出错，必须用空格。
 * - 本例不判断 b^2-4ac<0；若判别式为负，sqrt 会得到 NaN（题目已保证 >0）。学到下一章选择结构后，应先用 if 检查判别式是否 >=0。
 *
 * 内存与编译器原理：
 * - &a 取出变量 a 的内存地址传给 scanf，scanf 按该地址把值写入 a 的存储单元。
 * - double 占 8 字节，%lf 告诉 scanf 按 8 字节双精度格式解释输入。
 * - %7.2f 是"最小字段宽 7、精度 2"，不足 7 列左补空格，实现右对齐。
 * - printf/scanf 是库函数，编译时只生成调用、不翻译进目标码，链接阶段才与系统函数库连接（这也是为什么要 #include 声明）。
 * - 输出用英文/ASCII（x1=、x2= 及数字本就 ASCII），跨平台不乱码。
 */

#include <stdio.h>            /* 程序中要调用标准输入输出函数 printf、scanf */
#include <math.h>             /* 程序中要调用求平方根函数 sqrt */

int main()                    /* 定义主函数 */
{
    double a, b, c, disc, x1, x2, p, q;   /* disc 用来存放判别式(b*b-4ac)的值 */
    scanf("%lf%lf%lf", &a, &b, &c);       /* 输入双精度型变量的值要用格式声明"%lf" */
    disc = b * b - 4 * a * c;             /* 计算判别式 */
    p = -b / (2.0 * a);                   /* 公共部分 p = -b/(2a) */
    q = sqrt(disc) / (2.0 * a);           /* q = sqrt(判别式)/(2a) */
    x1 = p + q; x2 = p - q;               /* 求出方程的两个根 */
    printf("x1=%7.2f\nx2=%7.2f\n", x1, x2);   /* 输出方程的两个根，%7.2f 定宽 2 位小数 */
    return 0;                             /* 程序正常结束 */
}

