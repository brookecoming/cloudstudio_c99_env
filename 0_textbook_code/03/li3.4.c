/*
 * 例 3.4：给出三角形的三边长，求三角形面积。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（海伦公式，也是 §3.4「赋值语句」的引例）：
 * 已知三角形三边 a、b、c，求面积用海伦公式：area = sqrt( s*(s-a)*(s-b)*(s-c) )，其中 s=(a+b+c)/2 是半周长。
 * 给定 a=3.67、b=5.43、c=6.21，代入即可算出面积。
 * 解题关键有两条：一是找到正确的数学公式，二是会用 C 的数学函数 sqrt() 实现开平方。
 *
 * 解题思路（顺序结构，从上到下依次执行）：
 * ① 定义 a、b、c、s、area 五个双精度变量（double，为提高精度）。
 * ② 分别给三边 a、b、c 赋值。
 * ③ 计算半周长 s = (a+b+c)/2。
 * ④ 计算面积 area = sqrt(s*(s-a)*(s-b)*(s-c))。
 * ⑤ 用 printf 输出三边 a、b、c（用 \t 分隔对齐）。
 * ⑥ 用 printf 输出面积 area。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - 求面积要连乘、开方，几个变量全部定义成 double，比 float 精度高、末位误差小。
 * - sqrt() 是求平方根的函数，属于数学函数库；调用它必须在文件开头加 #include <math.h>，把 math.h 头文件包含进来。
 * - printf 格式串里的 \t 是转义字符，作用是"使输出位置跳到下一个 Tab 位置"；一个 Tab 区占 8 列，用 \t 能把多个数据调得清晰、整齐、美观。
 * - \n 是换行；\t 与 \n 别混淆。
 * - 课本提醒：以后凡在程序中要用数学函数库里的函数，都应当在文件开头包含 math.h 头文件。
 *
 * 【本节配套知识点：赋值语句（对应课本 §3.4 归纳）】
 * 1. 赋值运算符 "="：把一个数据赋给一个变量。a=3 是把常量 3 赋给 a；右侧也可以是表达式，如 s=(a+b+c)/2。
 * 2. 复合赋值运算符：在 "=" 前加上其他运算符，构成 +=、-=、*=、/=、%=。
 *    a+=3 等价于 a=a+3；x*=y+8 等价于 x=x*(y+8)；x%=3 等价于 x=x%3。
 *    记忆口诀：把带下划线的左半"移到"右侧、左侧补回原变量名。
 *    关键易错：复合赋值右边的表达式"相当于自带括号"。x*=y+8 是 x=x*(y+8)，绝不是 x=x*y+8；x%=y+3 是 x=x%(y+3)，不要错写成 x=x%y+3。
 * 3. 赋值表达式：由"变量 赋值运算符 表达式"连接起来的式子，兼具"计算 + 赋值"双重功能；整个表达式也有值，且值等于赋值后左侧变量的值。
 *    a=3*5 求值后 a 为 15、表达式值也为 15；a=b=c=5 按"自右向左"结合，a、b、c 全为 5；a=(b=3*4) 先算 b=12 再赋给 a，a、b 都等于 12。
 *    左值(lvalue)/右值(rvalue)：赋值号左侧必须是"可改值的左值"（如变量），常量和 a+b 这类表达式不能作左值；能出现在右侧的称为右值。
 *    赋值表达式还能嵌进别的语句，如 printf("%d", a=b); 一行里同时完成赋值和输出，这是 C 语言灵活性的体现。
 * 4. 赋值过程中的类型转换：赋值号两侧类型一致时直接赋值；不一致时（如把实型赋给整型）会按规则转换，这个下一节还会展开。
 *
 * 难点：
 * - "数学公式 → C 表达式"的翻译：sqrt(s*(s-a)*(s-b)*(s-c)) 里每个乘号 * 都不能省略。
 * - \t 的对齐效果取决于它前面已经输出了多少个字符（一个 Tab 区 8 列）。
 * - 复合赋值"右侧整体加括号"这一点最容易记反。
 *
 * 易错易混点：
 * - 用了 sqrt 却忘了 #include <math.h>，会隐式声明、结果不对。
 * - 数学里 s(s-a)(...) 省略了乘号，C 语言绝不能省，必须写成 s*(s-a)*...。
 * - 变量本应定义 double，若图省事用 float，末位误差更大。
 * - 以为 x*=y+8 是 x=x*y+8，正解是 x=x*(y+8)。
 *
 * 内存与编译器原理：
 * - double 通常占 8 字节，有效数字约 15~16 位，比 float（4 字节、6~7 位）多。
 * - sqrt 是标准库函数，编译时生成对它的调用，链接阶段从数学库引入实现。
 * - 赋值表达式自右向左结合，所以 a=b=c=5 等价于 a=(b=(c=5))。
 * - 输出用英文/ASCII（a=、b=、area= 及数字本就是 ASCII），跨平台不乱码。
 */

#include <stdio.h>            /* 包含标准输入输出库，提供 printf */
#include <math.h>             /* 包含数学函数库，提供 sqrt（求平方根）*/

int main()                    /* 定义主函数 */
{
    double a, b, c, s, area;  /* 定义各变量，均为 double 型（双精度，提高精度）*/
    a = 3.67;                 /* 对边长 a 赋值 */
    b = 5.43;                 /* 对边长 b 赋值 */
    c = 6.21;                 /* 对边长 c 赋值 */
    s = (a + b + c) / 2;      /* 计算半周长 s = (a+b+c)/2 */
    /* 用海伦公式计算面积；注意 C 里每个乘号 * 都不能省略 */
    area = sqrt(s * (s - a) * (s - b) * (s - c));   /* 计算 area */
    printf("a=%f\tb=%f\tc=%f\n", a, b, c);          /* 输出三边 a,b,c，\t 制表对齐 */
    printf("area=%f\n", area);                       /* 输出面积 area 的值 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * a=3.670000	b=5.430000	c=6.210000
 * area=9.903431
 *
 * 【实测与课本末位不同，如实记录】课本(P60)运行结果印的是 area=9.798341。
 * 但按公式与三边值 a=3.67、b=5.43、c=6.21 实际算：半周长 s=7.655，
 * area = sqrt(7.655×3.985×2.225×1.445) ≈ 9.903431，本机结果才是按公式的正确值。
 * 代码与课本一字不差，课本那一版此处数字系印刷差异；对照发现不同以"公式 + 程序实算"为准，不是代码写错。
 *
 * 【运行与演示】本例不需要键盘输入，三边值直接写在程序里。
 * 想验证海伦公式可把三边改成 3、4、5（直角三角形），看 area 是否变成 6.000000。
 * 也可把某个数改大一位，观察 \t 如何把后面的列顶到下一个 8 列格，体会制表对齐效果。
 */

/*
 * 【讲解过程稿】（本稿骨架照搬课本例 3.4 自己的小标题：解题思路 → 编写程序 → 运行结果 → 程序分析）
 *
 * 开场：给你三角形的三条边，不用量高就能算面积——数学家海伦给了一个只靠三边的公式，这题把它写成程序。【互动停顿：问“求面积一般要底和高，可这里没给高，怎么办？”停 2~3 秒】
 * 解题思路（对应课本“解题思路”）：课本点破关键——解此题的关键是找到求三角形面积的公式。先假设三条边能构成三角形（任意两边之和大于第三边），海伦公式：先算半周长 s=(a+b+c)/2，再 area=√(s(s−a)(s−b)(s−c))。公式定了，剩下就是把它一行行翻译成赋值。
 * 编写程序（对应课本“编写程序”：根据上面的公式写）：
 *   - double a,b,c,s,area; 五个量全用双精度，因为要连乘开方，float 精度不够。
 *   - a=3.67; b=5.43; c=6.21; 把三条边赋值进去，这就是最基本的赋值语句。
 *   - s=(a+b+c)/2; 先算半周长，注意 C 里乘号除号都不能省。
 *   - area=sqrt(s*(s-a)*(s-b)*(s-c)); 调 sqrt 开平方，所以文件开头必须 #include <math.h>。
 *   - 两个 printf 用 \t 把三边对齐、再换行输出面积，屏幕就整齐了。
 * 运行结果（对应课本“运行结果”）：跑一遍，屏幕按 \t 对齐打印出三条边，再输出算好的面积 area。
 * 程序分析（对应课本“程序分析”，本例最该强调的一处）：最该提醒的是 sqrt 和 math.h 是绑在一起的——用了开方却忘包头文件，程序要么报错要么结果不对；还有那句“乘号一个都不能省”：数学里 s(s-a) 能并写，C 里必须写成 s*(s-a)。
 * 收尾：这题把“公式翻译成 C 表达式 + 赋值语句 + 调库函数 + \t 对齐”串成一条线。留个问题：如果我把 area=sqrt(...) 写成 s(s-a)(s-b)(s-c) 省掉乘号，编译能过吗？【互动停顿：留几秒，再揭晓“C 语言不认，乘号一个都不能省，会编译报错”】
 */

