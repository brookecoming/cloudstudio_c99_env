/*
 * 例 3.6：用 %f 输出实数，只能得到 6 位小数。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（§3.7 格式输出的"实数输出"）：
 * a=1.0 是双精度型，a/3 的结果也是双精度型，但用 %f 输出时只得到 6 位小数（0.333333），并非把全部精度都打印出来。
 * 本例就是用一个最短的程序引出"实数到底能输出几位、由什么决定"这件事。
 *
 * 解题思路（顺序结构）：
 * ① 定义双精度变量 a 并赋初值 1.0。
 * ② 用 printf 以 %f 格式输出 a/3 的值。
 * ③ 观察：结果只保留 6 位小数。
 *
 * 关键知识点（对应课本 §3.7 格式输出）：
 * - ① f 格式符基本型 %f：不指定输出长度，由系统按数据实际情况决定列数；一般实数整数部分全部输出、小数部分输出 6 位。
 * - ② 指定宽度和小数位数用 %m.nf：m 是输出总宽度（占几列），n 是小数位数（第 n+1 位四舍五入）。例 3.5 的 %7.2f 就是占 7 列、含 2 位小数。
 * - 若小数位数 n 指定为 0，不仅不输出小数、连小数点也不输出：%7.0f 输出 a/3 时整数部分为 0，结果只打印 0。所以别轻易把 n 设为 0。
 * - 想输出 15 位小数，把本例第 4 行改为 printf("%20.15f\n",a/3);，即占 20 列、15 位小数，注意 0 前面有 3 个空格（不足总宽左补空格）。
 * - s 格式符：用来输出一个字符串，如 printf("%s","CHINA"); 在屏幕输出 CHINA（不包括双引号）。
 *
 * 难点：
 * - 区分"数据的精度"和"输出的位数"：double 能存约 15 位有效数字，但 %f 默认只打印 6 位小数——这是输出格式限制的，不是数据丢了。
 * - 理解 %m.nf 里 m（总宽）和 n（小数位）各管什么。
 *
 * 易错易混点：
 * - 误以为 %f 输出几位就说明该数只有几位精度：其实输出位数由格式控制，数据本身精度由类型决定。
 * - 用 %50.50f 想打 50 位真值也打不出：双精度只能保证 15 位有效数字，多出的位是不可靠的凑数位，别以为计算机输出的数字都绝对精确。
 * - 有效数字上限要记牢：float 只保证约 6 位有效数字，double 保证约 15 位有效数字。
 *
 * 内存与编译器原理：
 * - a=1.0 存为 double（8 字节），a/3 是浮点除法，结果仍是 double。
 * - printf 的 %f 默认精度 6 位，是把二进制双精度值按格式舍入后的十进制呈现。
 * - %20.15f 中 20 是最小字段宽度，不足则左补空格，所以 0 前面会有若干空格。
 * - 输出用英文/ASCII（0.333333 本就是 ASCII 数字），跨平台不乱码。
 */

#include <stdio.h>            /* 包含标准输入输出库，提供 printf */

int main()                    /* 定义主函数 */
{
    double a = 1.0;           /* 定义双精度变量 a 并赋初值 1.0 */
    printf("%f\n", a / 3);    /* 用 %f 输出 a/3，默认只保留 6 位小数 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * 0.333333
 * 虽然 a 是双精度型、a/3 的结果也是双精度型，但用 %f 只能输出 6 位小数，与课本一致。
 *
 * 【运行与演示】本例不需要键盘输入，点 ▶ 运行即可看到 0.333333。
 * 动手改一行：把第 4 行改成 printf("%20.15f\n", a / 3); 再运行，输出变为下面这样（0 前有 3 个空格，共占 20 列）：
 *        0.333333333333333
 * 这时输出了 15 位小数。但双精度只能保证 15 位有效数字，即使指定 %55.50f 也不能保证 50 位都有效——多出来的是凑数位。
 *
 * 【小结记忆】
 *   %f      → 默认 6 位小数
 *   %m.nf   → 总宽 m 列、小数 n 位（第 n+1 位四舍五入）
 *   float 有效数字 ≈ 6 位；double 有效数字 ≈ 15 位
 */

