/*
 * 例 3.2：计算存款利息。有 1000 元，想存一年，有三种方法可选：
 *        (1) 活期，年利率为 r1；(2) 一年期定期，年利率为 r2；(3) 存两次半年定期，年利率为 r3。
 *        请分别计算出一年后按三种方法所得到的本息和。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（还是顺序结构，只是"一口气算三个结果"）：
 * 同一笔本金，用三种不同的存法，各算一年后的本息和（本金加利息）。
 * 它比例 3.1 多了一件事：一个程序里可以并行算出好几个结果，只要按公式一条条赋值、最后一起输出就行。
 *
 * 解题思路（对应课本图 3.2 的 N-S 盒图，全是顺序执行）：
 * ① 备好多组数据：本金 p0 和三个年利率 r1、r2、r3，并赋初值。
 * ② 算活期本息和 p1 = p0 * (1 + r1)。
 * ③ 算一年定期本息和 p2 = p0 * (1 + r2)。
 * ④ 算两次半年定期本息和 p3 = p0 * (1 + r3/2) * (1 + r3/2)。
 * ⑤ 一次性输出 p1、p2、p3。
 *
 * 关键知识点：
 * - 定义变量时同时赋初值：float p0=1000, r1=0.0036, ...; 一行里定义并给多个变量赋值。
 * - 本息和公式：活期和一年定期都是 p0*(1+r)；半年定期因为一年滚动两次，所以乘两次 (1+r3/2)。
 * - 一次 printf 输出多个值：格式串里写几个 %f，后面就按顺序跟几个变量，用 \n 分行。
 * - 顺序结构：所有语句依旧自上而下依次执行，没有判断和循环。
 *
 * 难点：
 * - 理解"两次半年定期"为什么要乘两个 (1+r3/2)：上半年利息并入本金，下半年再按同样利率滚一次，这就是复利的雏形。
 * - 理解 r3/2 是把年利率折成半年利率，别和 r3 本身混了。
 *
 * 易错易混点：
 * - p3 写成 p0*(1+r3) 就漏掉了"半年滚两次"，结果偏小；正确是 p0*(1+r3/2)*(1+r3/2)。
 * - 年利率是百分数，代入时要写成小数（如 2.25% 写 0.0225），别直接写 2.25。
 * - 这些实型常量（1000、0.0036…）在 C 里默认按 double 处理，赋给 float 变量会发生精度转换（见文末"注意"）。
 * - printf 里 %f 的个数要和后面变量个数一一对应，多了少了都会出错。
 *
 * 内存与编译器原理：
 * - p0、r1、r2、r3、p1、p2、p3 都是 float，各占 4 字节。
 * - 实型常量默认是 double，赋值给 float 时被转换成单精度，可能有轻微精度损失。
 * - 课本"注意"栏特别指出：在 Visual C++ 6.0 里把 double 常量赋给 float 会弹"警告"，而用 GCC 编译则不会有这个警告，两者运行结果一致。
 * - %f 输出时按 6 位小数打印，末尾数字受 float 有效位数限制，不同编译器可能略有出入。
 */

#include <stdio.h>            /* 引入标准输入输出库，提供 printf 函数 */

int main()                    /* 主函数，程序从这里开始执行 */
{
    /* 定义变量，并在定义的同时赋初值：本金 p0 和三种年利率 */
    float p0 = 1000, r1 = 0.0036, r2 = 0.0225, r3 = 0.0198, p1, p2, p3;
    p1 = p0 * (1 + r1);               /* 计算活期本息和 */
    p2 = p0 * (1 + r2);               /* 计算一年定期本息和 */
    p3 = p0 * (1 + r3 / 2) * (1 + r3 / 2);   /* 计算存两次半年定期的本息和 */
    printf("p1=%f\np2=%f\np3=%f\n", p1, p2, p3);   /* 一次输出三个结果，\n 分行 */
    return 0;                 /* 程序正常结束 */
}

