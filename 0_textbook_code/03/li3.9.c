/*
 * 例 3.9：从键盘输入 BOY 3 个字符，然后把它们输出到屏幕。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（§3.5.5 字符输入函数 · getchar）：
 * 承接例 3.8 的 putchar（输出字符），这里学配套的输入函数 getchar。
 * getchar 是 "get character"（取得字符）的缩写，没有参数，从计算机终端（一般是键盘）输入一个字符，函数值就是从输入设备得到的字符。
 * getchar 一次只能接收【一个】字符，想输入多个字符就要用多个 getchar 函数。
 * 本例用 3 次 getchar 读入 B、O、Y，再用 3 次 putchar 输出。
 *
 * 解题思路（顺序结构）：
 * ① 定义 3 个字符变量 a、b、c。
 * ② a=getchar() 读一个字符给 a。
 * ③ b=getchar() 读一个字符给 b。
 * ④ c=getchar() 读一个字符给 c。
 * ⑤ putchar(a/b/c) 依次输出，最后 putchar('\n') 换行。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - getchar() 无参数，返回从键盘读入的一个字符；一次只读一个字符。
 * - 输入是"按行缓冲"的：敲的字符先暂存在键盘缓冲区，只有按下 Enter 才把整行一起送进程序，再按先后顺序逐个赋给相应变量。所以运行时要连续输入 BOY 再按 Enter。
 * - getchar 读到的字符可赋给字符变量或整型变量，也可不赋给任何变量、而作为表达式的一部分，如教材改写：putchar(getchar()); 读一个立即输出一个。
 * - 也可与 printf 结合：printf("%c", getchar());  读一个字符并用 %c 输出（%c 是输出字符的格式声明）。
 * - 执行 getchar 不仅能从输入设备获得可显示字符，也能获得屏幕上无法显示的字符，如控制字符。
 *
 * 难点（本例最值得讲的一处）：
 * - 缓冲区里"换行符也算一个字符"：若每输入 1 个字符就按一次 Enter，第 1 行送进来的其实是两个字符——'B' 和换行符 '\n'。于是 a 得到 'B'、b 却得到 '\n'、c 得到 'O'……输出就会分行错乱（教材演示：输入 B↵O↵ 会分两行输出 B 和 O）。正确做法：连续输入 BOY 后只按一次 Enter，让 3 个字符依次进 a、b、c。
 *
 * 易错易混点：
 * - 不要在按 B 后马上按回车，否则回车也被当作一个字符读入，打乱 a、b、c 的对应。
 * - getchar 一次一个字符，想读 3 个必须调用 3 次（getchar(a,b,c) 是错的）。
 * - getchar 与 scanf("%c") 都能读字符，但 getchar 无参数、直接返回读到的字符。
 *
 * 内存与编译器原理：
 * - 键盘输入先进入标准输入的缓冲区（buffer），Enter 后才供 getchar 逐个取出。
 * - getchar 返回值类型是 int（能表示所有字符及 EOF），赋给 char 会截取低 8 位。
 * - '\n' 在缓冲区中占一个字符位，这是"多按回车会读出错乱"的根本原因。
 * - 输出用英文/ASCII（BOY 本就是 ASCII 字母），跨平台不乱码。
 */

#include <stdio.h>            /* 包含标准输入输出库，提供 getchar、putchar */

int main()                    /* 定义主函数 */
{
    char a, b, c;             /* 定义字符变量 a、b、c */
    a = getchar();            /* 从键盘输入一个字符，送给字符变量 a */
    b = getchar();            /* 从键盘输入一个字符，送给字符变量 b */
    c = getchar();            /* 从键盘输入一个字符，送给字符变量 c */
    putchar(a);               /* 将变量 a 的值输出 */
    putchar(b);               /* 将变量 b 的值输出 */
    putchar(c);               /* 将变量 c 的值输出 */
    putchar('\n');            /* 换行 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测，键入 BOY 后按一次 Enter）：
 * BOY        <- 这是你键入并回显的内容
 * BOY        <- 这是程序用 putchar 输出的内容
 * 与课本一致：连续输入 BOY 并按 Enter 后，字符才送到计算机中，然后输出 BOY 并换行。
 *
 * 【运行与演示】本例用 getchar 从键盘读入，点 ▶ 运行后程序会停下等你输入。
 * 请【连续输入 BOY 再按一次 Enter】（不要每敲一个字母就按回车），程序把 B、O、Y 依次读进 a、b、c 后输出。
 * 动手试错乱：若输入 B↵O↵（每字母都回车），会分两行输出 B 和 O——因为第 1 行的换行符被读进了 b。
 *
 * 【课本改写】整个函数体可不引入变量、边读边输出：putchar(getchar()); 三次 + putchar('\n');
 *   第 1 个 putchar(getchar()) 相当于 putchar('B')，输入 BOY 回车后同样输出 BOY。
 *   也可用 printf 输出刚读的字符：printf("%c", getchar());  // %c 是输出字符的格式声明。
 */

/*
 * 【讲解过程稿】（本稿骨架照搬课本例 3.9 自己的小标题：解题思路 → 编写程序 → 运行结果 → 说明）
 *
 * 开场：上一题 putchar 往屏幕上放字符，这题反过来——从键盘往程序里收字符，主角叫 getchar。【互动停顿：问“从名字猜，它和 putchar 谁读谁写？”停 2~3 秒】
 * 解题思路（对应课本“解题思路”）：课本点破——用三个 getchar 函数先后从键盘向计算机输入 B、O、Y 三个字符，然后用 putchar 函数输出。就是把“读一个字符”和“放一个字符”各重复三遍。
 * 编写程序（对应课本“编写程序”）：
 *   - char a,b,c; 三个字符变量准备接键盘来的字符。
 *   - a=getchar(); b=getchar(); c=getchar(); getchar 没有参数，它从键盘取一个字符当返回值；连续调用三次，就把 B、O、Y 分别装进 a、b、c。
 *   - putchar(a); putchar(b); putchar(c); 挨个输出，putchar('\n') 换行。
 * 运行结果（对应课本“运行结果”）：连续输入 BOY 并按回车，屏幕输出 BOY。
 * 说明（对应课本“注意/说明”，本例最该强调的一处）：这里有个大坑——键盘输入是按行缓冲的，你敲的字符先暂存在键盘缓冲区，按下回车才整行送进来，而且回车本身也算一个字符。所以必须“连续敲 BOY 再按一次回车”；要是每敲一个字母就按回车，第二个 getchar 读到的就是换行符，输出立刻错乱分行。课本还给了个合并写法 putchar(getchar()); 读一个立刻输出一个，不必存变量。
 * 收尾：这题让我们记住 getchar 一次读一个字符、输入按行缓冲、回车也是字符。留个问题：我输入 B 就按回车、再输入 O 按回车，程序最后会输出什么？【互动停顿：留几秒，再揭晓“a 收到 B、b 收到回车、c 收到 O，于是先输出 B 换一行、再输出 O，看着像分了行”】
 */

