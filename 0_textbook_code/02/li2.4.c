/*
 * 例 2.4：求 1 - 1/2 + 1/3 - 1/4 + … + 1/99 - 1/100 的值
 * 【本文件严格对照教材 图 2.11 的流程图实现】
 *
 * 题目背景：
 * --------
 * 这是一个"交替级数"（各项符号正负相间）。把多项式抽象成"一般项 + 循环累加"：
 *   ① 第 1 项固定为 1（即 1/1），先放进 sum；
 *   ② 从第 2 项起，分母 deno 每次 +1（2、3、4…100）；
 *   ③ 每项符号与前一项相反，用 sign 每次乘 (-1) 翻转。
 * 教材用有意义的英文名：sign(符号)、term(当前项)、sum(累加和)、deno(分母)。
 *
 * 图 2.11 的结构（逐框对应）：
 * --------------------------
 *   框 1 => sum
 *   框 2 => deno
 *   框 1 => sign
 *   —— 以下为"直到型循环"：先执行循环体，再在底部判断 ——
 *   框 (-1) * sign => sign        （符号翻转）
 *   框 sign * (1 / deno) => term  （求当前项；C 里须写 1.0/deno 才是小数）
 *   框 sum + term => sum          （累加）
 *   框 deno + 1 => deno           （分母 +1）
 *   判断框 deno > 100?  N -> 回到"(-1)*sign"框继续;  Y -> 输出 sum
 *   输出 sum
 * 底部判断的直到型对应 C 的 do…while；do-while 写"继续"条件，与流程图"结束"条件
 * deno>100 互反，故等价写 while (deno <= 100)。
 *
 * 关键知识点：
 * ----------
 * - 直到型循环 do…while：先做后判断，循环体至少执行一次；末尾分号不能漏
 * - 问题抽象：找规律 → 用少量变量(sign/term/sum/deno) + 循环 表达一长串项
 * - 符号翻转技巧：sign = (-1) * sign，让 +1 / -1 交替
 * - 浮点除法：被除数或除数至少一个是浮点数才得小数（见下方最大坑）
 *
 * 难点：
 * ----
 * - 理解 sign = (-1)*sign 如何产生 +、-、+、-…：初值 1，每次乘 -1 交替
 * - 理解 sum 初值为 1、循环从 deno=2 开始：第 1 项已单独放入 sum，循环负责第 2~100 项
 *
 * 易错易混点：
 * ----------
 * - 【最大坑】写成 1 / deno（两个 int 相除）→ 整数除法结果为 0，整个和变成 1！
 *   必须写 1.0 / deno（或 (double)1 / deno）才是小数（流程图"1/deno"是数学实数除法）
 * - do…while 的 } 后必须有分号
 * - sum、term 若定义成 int，小数部分被截断，必须用 double
 * - 循环继续条件 deno <= 100（含最后一项 1/100），写成 deno < 100 会漏 1/100
 * - sign、sum、deno 三个初值必须配套（1、1、2），改一个要检查另两个
 *
 * 内存与编译器原理：
 * ----------------
 * - int / 1 是整数除法：结果截断为 0（如 1/2=0）；1.0/deno 时 deno 隐式提升为 double 再浮点除
 * - double 占 8 字节、约 15~16 位有效数字；累加 99 项的舍入误差对本量级可忽略
 * - sign 用 int 存 ±1 足够；term、sum 用 double 才能保存小数
 * - 输出用英文，避免 Windows 控制台 GBK 下中文乱码（红线规则）
 */

#include <stdio.h>        /* 包含标准输入输出库，提供 printf */

int main()                /* 定义主函数 */
{
    double sum = 1;       /* 框: 1 => sum，先放入第 1 项 1（用 double 保存小数） */
    int deno = 2;         /* 框: 2 => deno，分母从 2 开始（对应第 2 项 1/2） */
    int sign = 1;         /* 框: 1 => sign，符号初值 +1 */
    double term;          /* 对应流程图的 term 框：存放当前项的值（含符号） */

    /* 直到型循环：先执行四个处理框，再在底部判断 deno>100（对应图 2.11） */
    do
    {
        sign = (-1) * sign;            /* 框: (-1) * sign => sign，符号翻转 */
        term = sign * (1.0 / deno);    /* 框: sign*(1/deno) => term，1.0 保证浮点除法 */
        sum = sum + term;              /* 框: sum + term => sum，累加当前项 */
        deno = deno + 1;               /* 框: deno + 1 => deno，准备下一项 */
    } while (deno <= 100);             /* 判断框 deno > 100?：N(即 deno<=100) 返回循环体，Y 退出 */

    printf("sum = %f\n", sum);         /* 输出框: 输出 sum，结果约为 0.688172 */

    return 0;             /* 程序正常结束 */
}

