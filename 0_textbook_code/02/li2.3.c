/*
 * 例 2.3：判定 2000—2500 年中的每一年是否为闰年，并将结果输出
 * 【本文件严格对照教材 图 2.10 的流程图实现】
 *
 * 题目背景：
 * --------
 * 闰年判定条件（教材给出）：
 *   (1) 能被 4 整除，但不能被 100 整除的年份是闰年（如 2004）
 *   (2) 能被 400 整除的年份是闰年（如 2000、2400）
 *   不符合以上两条的都不是闰年（如 2001、2100）
 * 要逐个检查 2000 到 2500 共 501 个年份，是"循环 + 多分支判断"的典型。
 *
 * 图 2.10 的结构（逐框对应）：
 * --------------------------
 *   框 2000 => year                       （循环前赋值，初值）
 *   —— 以下为"直到型循环"：先执行循环体，再在底部判断 ——
 *   判断框1: year 不能被 4 整除?  Y -> 输出"不是闰年";  N -> 进入判断框2
 *   判断框2: year 不能被 100 整除? Y -> 输出"是闰年";    N -> 进入判断框3
 *   判断框3: year 不能被 400 整除? Y -> 输出"不是闰年";  N -> 输出"是闰年"
 *   框 year + 1 => year                   （换下一年）
 *   判断框: year > 2500?  N -> 回到判断框1 继续;  Y -> 结束
 * 三个判断框"层层深入"，对应 C 的**嵌套 if—else**；底部判断的直到型对应 **do…while**。
 * do-while 写"继续"条件，与流程图"结束"条件 year>2500 互反，故等价写 while (year <= 2500)。
 *
 * 关键知识点：
 * ----------
 * - 直到型循环 do…while：先做后判断，末尾分号不能漏
 * - 嵌套 if—else：每个判断框的 N 分支下降到下一层，忠实还原流程图的层次
 * - 取余判整除："不能被 X 整除" 写作 year % X != 0（照图用 != 0 的负极性）
 * - 判断顺序 4 -> 100 -> 400 由外到内，不可颠倒
 *
 * 难点：
 * ----
 * - 为什么用"嵌套 if—else"而不是平铺的 else if 链：为忠实对应图 2.10 判断框层层
 *   深入的画法（两者逻辑等价，但嵌套结构与流程图一一对应，便于按图讲解）
 * - 最内层 else（能被400整除）才输出"是闰年"：走到这里说明能被4、能被100，
 *   只剩能否被400这一个关卡
 *
 * 易错易混点：
 * ----------
 * - do…while 的 } 后必须有分号
 * - 判断框是"不能被整除"(!=0)，别把极性写反导致闰年/非闰年对调
 * - 顺序若把 400 的判断放到 100 前面，会错判世纪年
 * - 循环继续条件 year <= 2500（含 2500），写成 year < 2500 会漏 2500 年
 * - 忘记 year = year + 1 会死循环
 *
 * 内存与编译器原理：
 * ----------------
 * - year 是 int(4 字节)在栈上，循环中不断自增覆盖旧值
 * - % 取余底层是除法指令求余数，判整除开销很小；嵌套分支编译成一串条件跳转
 * - 输出 501 行走带缓冲的标准输出，程序结束前统一刷新，很快
 * - 输出用英文，避免 Windows 控制台 GBK 下中文乱码（红线规则）
 */

#include <stdio.h>        /* 包含标准输入输出库，提供 printf */

int main()                /* 定义主函数 */
{
    int year = 2000;      /* 框: 2000 => year，从 2000 年开始检测 */

    /* 屏幕输出用英文/ASCII(红线)：流程图里的"是闰年/不是闰年"标签在 printf 用英文替代。 */
    do                    /* 直到型循环：先执行判断与 year+1，再在底部判断 year>2500 */
    {
        if (year % 4 != 0)            /* 判断框1: year 不能被 4 整除? */
        {
            printf("%d is not a leap year\n", year);   /* Y: 不是闰年 */
        }
        else                           /* N: 能被 4 整除，进入下一层 */
        {
            if (year % 100 != 0)      /* 判断框2: year 不能被 100 整除? */
            {
                printf("%d is a leap year\n", year);   /* Y: 是闰年 */
            }
            else                       /* N: 能被 100 整除，进入下一层 */
            {
                if (year % 400 != 0)  /* 判断框3: year 不能被 400 整除? */
                {
                    printf("%d is not a leap year\n", year);  /* Y: 不是闰年 */
                }
                else                   /* N: 能被 400 整除 */
                {
                    printf("%d is a leap year\n", year);      /*   是闰年 */
                }
            }
        }

        year = year + 1;              /* 框: year + 1 => year，切换到下一年 */
    } while (year <= 2500);           /* 判断框 year > 2500?：N(即 year<=2500) 返回，Y 结束 */

    return 0;             /* 程序正常结束 */
}

/*
 * 运行结果片段（部分，输出为英文）：
 *   2000 is a leap year       （能被4、被100、被400整除 -> 框1 N、框2 N、框3 N -> 是闰年）
 *   2001 is not a leap year   （不能被4整除 -> 框1 Y -> 不是闰年）
 *   2004 is a leap year       （能被4不能被100整除 -> 框1 N、框2 Y -> 是闰年）
 *   2100 is not a leap year   （能被4、被100但不能被400整除 -> 框3 Y -> 不是闰年）
 *   2400 is a leap year       （能被400整除 -> 框3 N -> 是闰年）
 *   2500 is not a leap year   （能被4、被100但不能被400整除 -> 框3 Y -> 不是闰年）
 *
 * 等价的一行布尔写法（学完逻辑运算符后可对照，逻辑相同但不如嵌套版贴合流程图）：
 *   if ((year % 4 == 0 && year % 100 != 0) || (year % 400 == 0))  是闰年; else 不是;
 */
