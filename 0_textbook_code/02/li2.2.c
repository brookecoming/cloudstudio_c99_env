/*
 * 例 2.2（课堂演示版：7 个学生）——按教材 例 2.7 图 2.9（含"输入"的流程图）实现
 * 功能：输入若干学生的学号与成绩，输出成绩在 80 分以上（含 80）的学生的学号和成绩
 *
 * 为什么是 7 个？
 * --------------
 * 课本原题是 50 个学生，课堂上无法现场敲 50 行、不便演示，故按老师要求改为 7 个。
 * 想恢复 50：把程序里所有的 7 改成 50、数组大小 8 改成 51 即可，逻辑完全不变。
 *
 * 数据模型（决定变量形式）：
 * ------------------------
 * 流程图用带下标的 n_i、g_i 表示"第 i 个学生的学号/成绩"，是**一批同类数据**，
 * 故用数组落地：int id[8]、int g[8]（下标 1~7 对应第 1~7 个学生，浪费 [0] 换编号直观）。
 *
 * 图 2.9 的结构 = 两个"直到型"循环（先执行循环体，再在底部判断 i>7；N 返回、Y 向下）：
 *   阶段①输入循环：  1⇒i → [ 输入 n_i,g_i → i+1⇒i → 判 i>7? ](N回输入)
 *   然后 1⇒i 重置
 *   阶段②输出循环：  [ 判 g_i>=80? →(Y)输出 n_i,g_i → i+1⇒i → 判 i>7? ](N回判断)
 * 直到型循环对应 C 的 do…while。注意 do-while 写"继续"条件，与流程图"结束"条件 i>7 互反，
 * 故等价写成 while (i <= 7)。
 *
 * 关键知识点：
 * ----------
 * - 直到型循环 do…while：先做后判断，循环体至少执行一次；末尾分号不能漏
 * - 数组按下标存取一批数据：id[i]、g[i] 一一对应第 i 个学生
 * - 输入与处理分成两个独立循环（图 2.9 本就是这样），这正是"输入/输出解耦"的规范做法
 * - 判断框方向：流程图判"是否结束(i>7)"，do-while 判"是否继续(i<=7)"，两者互反
 *
 * 难点：
 * ----
 * - 看懂图 2.9 有"两个循环 + 中间一次 i 重置"：第一个只管把数据读进数组，
 *   第二个才遍历数组做筛选输出；数据靠数组在两个循环之间留存
 * - 理解输入循环里"先输入后 i+1 再判断"：i 从 1 输入到 7，i 变 8 时 i>7 成立退出
 *
 * 易错易混点：
 * ----------
 * - do…while 的 } 后必须有分号
 * - 数组大小要 >= 8（下标用到 7），开 id[7] 会下标越界
 * - 边界 g[i] >= 80（含 80），写成 > 80 会漏掉正好 80 分的学生
 * - 两个循环都要先把 i 置 1（尤其第二个循环前的"1⇒i"重置不能漏，否则 i 停在 8 直接结束）
 *
 * 内存与编译器原理：
 * ----------------
 * - id、g 各 8 个 int（栈上各 32 字节），元素连续存放，可用下标随机访问
 * - 阶段①把数据写入数组后"留存"，阶段②重置 i 再读取——数据能跨循环存在正是数组的价值
 * - 输出用英文，避免 Windows 控制台 GBK 下中文乱码（红线规则）
 */

#include <stdio.h>        /* 包含标准输入输出库，提供 printf / scanf */

int main()                /* 定义主函数 */
{
    int id[8];            /* n1~n7：7 个学生的学号（下标 1~7） */
    int g[8];             /* g1~g7：7 个学生的成绩（下标 1~7，与 id 对应） */
    int i;                /* 下标 / 循环变量 */

    /* ================= 阶段①：输入循环（对应图 2.9 上半，直到型 do…while） ================= */
    i = 1;                /* 框: 1 => i */
    do
    {
        printf("Enter ID and score of student #%d: ", i);
        scanf("%d %d", &id[i], &g[i]);   /* 框: 输入 n_i, g_i */
        i = i + 1;                       /* 框: i + 1 => i */
    } while (i <= 7);     /* 判断框 i>7?：为 N(即 i<=7) 返回继续输入；i=8 时退出 */

    /* ================= 阶段②：处理与输出循环（对应图 2.9 下半，直到型 do…while） ========== */
    i = 1;                /* 框: 1 => i（重置！第二个循环从头遍历） */
    printf("Students with score >= 80:\n");
    do
    {
        if (g[i] >= 80)   /* 判断框 g_i >= 80? */
            printf("ID=%d, score=%d\n", id[i], g[i]);   /* Y: 输出 n_i, g_i */
        i = i + 1;        /* 框: i + 1 => i */
    } while (i <= 7);     /* 判断框 i>7?：为 N(即 i<=7) 返回继续；i=8 时退出 */

    return 0;             /* 程序正常结束 */
}

