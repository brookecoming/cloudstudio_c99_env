/*
 * 例 2.18：将例 2.16 表示的算法（求 5!，即 1×2×3×4×5）用 C 语言表示。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于理解的中文注释】
 *
 * 题目背景（§2.5.6 用计算机语言表示算法——算法阶梯的最后一步）：
 * 前面例 2.1 用"步骤 S1~S5"（自然语言）描述算法，例 2.6 用流程图，例 2.16 用伪代码/N-S 图。
 * 本例是这条阶梯的终点：把同一个"求 5!"的循环算法，翻译成计算机能执行的 C 语言程序。
 * 用计算机语言表示算法必须严格遵循 C 的语法规则（这是它和伪代码最大的不同）。
 *
 * 解题思路（算法 S1~S5 → C 语句，一一对应）：
 * ① S1"1⇒t"（累乘器初值）→  t = 1;
 * ② S2"2⇒i"（乘数初值）    →  i = 2;
 * ③ S5"当 i≤5 时重复"（当型循环条件）→  while (i<=5) { ... }
 * ④ S3"t×i⇒t"（循环体）    →  t = t * i;
 * ⑤ S4"i+1⇒i"（循环体）    →  i = i + 1;
 * ⑥ 循环结束后输出 t        →  printf("%d\n", t);   结果为 120。
 *
 * 关键知识点（对应课本"用语言表示算法"）：
 * - 当型循环 while：先判断条件，条件为真(1)才执行循环体，为假(0)退出。与例 2.1 的 S5"若 i 不大于 5 则返回 S3"完全对应。
 * - 循环三要素：初值(t=1、i=2)、循环体(t=t*i; i=i+1;)、循环条件(i<=5)。
 * - 累乘器 t：每轮把 t*i 的结果覆盖回 t，始终存"到目前为止的乘积"。
 * - 算法→程序的翻译要点：伪代码/N-S 里的每一步，都要落成符合 C 语法的语句（分号、花括号、赋值号= 等一个都不能错）。
 *
 * 难点：
 * - 理解 while 是"当型"（先判断后执行），区别于例 2.1 流程图/例 2.6 的"直到型"（先执行后判断，用 do…while）。两者都能求 5!，但循环结构不同。
 * - 理解 t=t*i 不是数学等式，而是"把右边的值算出来再存回左边的 t"。
 *
 * 易错易混点：
 * - while 条件写 i<=5（当型：满足才循环）；若照搬流程图"i>5 退出"的逻辑，应写成 do…while(i<=5)。别把两种混在一起。
 * - while 后面没有分号：while(i<=5){ ... } 若写成 while(i<=5); 循环体就成空语句了。
 * - 循环体两条语句 t=t*i; i=i+1; 必须用花括号 { } 包起来（while 只管后面一条语句）。
 * - 先乘后自增顺序不能颠倒，否则跳过一个乘数。
 *
 * 内存与编译器原理：
 * - int 变量在 Windows 上通常占 4 字节，存 120 绰绰有余；求 13! 以上 int 会溢出，需 long long。
 * - 每轮 while 先读 i 判断，为真才进入循环体读改写 t、i。
 * - 局部变量 t、i 分配在栈上，main 结束自动释放。
 * - 输出用英文/ASCII（数字本就 ASCII），跨平台不乱码。
 */

#include <stdio.h>            /* 包含标准输入输出库，提供 printf */

int main()                    /* 定义主函数 */
{
    int i, t;                 /* 定义循环变量 i 和累乘器 t */
    t = 1;                    /* S1: 1⇒t，累乘器初值为 1 */
    i = 2;                    /* S2: 2⇒i，乘数从 2 开始 */
    while (i <= 5)            /* S5: 当 i≤5 时重复（当型循环条件）*/
    {
        t = t * i;            /* S3: t×i⇒t，把当前乘积覆盖回 t */
        i = i + 1;            /* S4: i+1⇒i，换下一个乘数 */
    }
    printf("%d\n", t);        /* 循环结束后输出 t，即 5! = 120 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * 120
 * 与课本一致：5! = 120。
 *
 * 执行跟踪（当型：先判断 i≤5，真才进循环体）：
 *  判断前 i   i≤5?   执行 t=t*i 后 t   执行 i+1 后 i
 *     2       真          2              3
 *     3       真          6              4
 *     4       真         24              5
 *     5       真        120              6
 *     6       假 —— 退出循环，输出 t=120
 *
 * 【运行与演示】本例不需要键盘输入，点 ▶ 运行即可看到 120。
 * 可改条件体会边界：把 i<=5 改成 i<=4 得 24(=4!)，改成 i<=6 得 720(=6!)。
 *
 * 【与例 2.1 的关系】例 2.1 是"算法怎么想"（S1~S5 步骤），本例是"算法怎么写成 C"。
 * 讲课时先回顾例 2.1 的 S1~S5 与循环思想，再逐条对应到本例的 C 语句，学生就懂"程序是算法的翻译"。
 */

/*
 * 【讲解过程稿】
 *
 * 开场：求 5! 这件事，前面我们已经用文字步骤、流程图、伪代码讲了好几遍"怎么想"。今天最后一步——把它翻译成计算机真能跑的 C 程序。【互动停顿：问"还记得例 2.1 那五步 S1 到 S5 吗？谁来说说 S5 是干嘛的？"停 2~3 秒】
 * 这题在干什么：把"求 5! 的循环算法"用 C 语言写成一个能运行的程序。
 * 大思路：先设两个初值 t=1、i=2，然后"只要 i 还没超过 5，就把 t 乘上 i、i 再加 1"，循环结束把 t 打印出来。
 * 逐块讲：
 *   - 第一块 t=1; i=2; 这就是算法的 S1、S2，给累乘器和乘数设初值。
 *   - 第二块 while(i<=5) 对应 S5 的判断"i 不大于 5 就继续"，是当型循环——先看条件，满足才进去。
 *   - 第三块 花括号里 t=t*i; i=i+1; 对应 S3、S4，是循环体：先累乘、再让乘数加 1。
 *   - 第四块 printf("%d\n",t); 循环退出后，t 里就是 120，打印出来。
 * 关键转折：一定要跟学生点透"算法和程序是两回事"——S1~S5 是算法，人可以看懂；但计算机只认 C 的语法，所以每个分号、每对花括号、while 后面不能加分号，都得严格照 C 的规矩来。这正是本节标题"用计算机语言表示算法"的意思。
 * 收尾：到这里，同一道求 5! 的题，我们走完了"自然语言→流程图→伪代码/N-S→C 程序"完整一条链。留个问题：本例用 while（先判断），例 2.1 的流程图是直到型 do…while（先执行），这两种写法结果一样吗？什么时候会不一样？【互动停顿：留几秒，再揭晓"本题恰好一样，都是 120；但若初值就让条件为假，while 一次都不执行、do-while 至少执行一次，结果就不同了"】
 */

