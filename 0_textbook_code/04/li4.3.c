/*
 * 例 4.3：输入 3 个数 a,b,c，要求按由小到大的顺序输出。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于讲解的中文注释】
 *
 * 题目背景（例 4.2 的升级版）：
 * 例 4.2 排两个数只要一次比较一次交换，这一例排三个数，比较和交换都要做三次。
 * 课本先用伪代码给出 S1~S4 四步算法，再翻译成 C，是"先算法后代码"的典型。
 *
 * 解题思路（对照课本 S1~S4）：
 * S1：if a>b，将 a 和 b 对换（交换后，a 是 a,b 中的小者）。
 * S2：if a>c，将 a 和 c 对换（交换后，a 是 a,c 中的小者，因此 a 是三者中最小者）。
 * S3：if b>c，将 b 和 c 对换（交换后，b 是 b,c 中的小者，也是三者中次小者）。
 * S4：顺序输出 a,b,c。
 * 翻译成 C 就是三个并列的 if，每个 if 里都是例 4.2 那套"借 t 三步交换"。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - 三次交换的目标是逐步"锁定"顺序：第一次让 a≤b，第二次让 a≤c（此时 a 已是最小），第三次让 b≤c。
 * - 三步做完后必有 a≤b≤c，所以直接顺序输出 a,b,c 就是由小到大。
 * - 每一处交换都和例 4.2 完全相同：t=x; x=y; y=t;，只是换的变量对不同。
 * - 三个 if 是并列关系（不是嵌套），各管一对变量的比较，顺序不能颠倒。
 *
 * 难点：
 * - 难点是理解"为什么三次就够了"：S1、S2 先把最小者赶到 a，S3 再收拾剩下的 b、c，分工明确。
 *
 * 易错易混点：
 * - 三个 if 的比较对象别抄错：依次是 a>b、a>c、b>c，写成 a>b、a>c、a>c 就乱了。
 * - 每处交换的三行内部顺序仍是 t=前; 前=后; 后=t;，别把 t 用错变量。
 * - scanf 是 "%f,%f,%f"，输入三个数之间要打两个逗号。
 *
 * 内存与编译器原理：
 * - a、b、c、t 四个独立内存格；三次交换共九次"读一格写一格"的搬移，t 全程当中转。
 * - 比较和交换都在 CPU 寄存器/内存里完成，没有函数调用开销，三个 if 是顺序执行的三条分支判断。
 * - 输出用 %5.2f 三次，每个数占 5 列 2 位小数，逗号分隔，列宽对齐便于肉眼核对顺序。
 */

#include <stdio.h>                  /* 引入标准输入输出库，提供 printf 和 scanf */

int main()                          /* 主函数 */
{
    float a, b, c, t;               /* a、b、c 放三个待排序的数，t 是交换用的中转变量 */

    scanf("%f,%f,%f", &a, &b, &c);  /* 读入三个实数，课本格式用逗号分隔，变量前要加 & */

    if (a > b)                      /* S1：a 比 b 大就把 a、b 互换 */
    {
        t = a;                      /* 借助 t，实现 a 和 b 互换值 */
        a = b;
        b = t;
    }                               /* 互换后，a 小于或等于 b */

    if (a > c)                      /* S2：a 比 c 大就把 a、c 互换 */
    {
        t = a;                      /* 借助 t，实现 a 和 c 互换值 */
        a = c;
        c = t;
    }                               /* 互换后，a 小于或等于 c，此时 a 已是三者最小 */

    if (b > c)                      /* S3：b 比 c 大就把 b、c 互换 */
    {
        t = b;                      /* 借助 t，实现 b 和 c 互换值 */
        b = c;
        c = t;
    }                               /* 互换后，b 小于或等于 c */

    printf("%5.2f,%5.2f,%5.2f\n", a, b, c);   /* S4：顺序输出 a,b,c，即由小到大 */
    return 0;                       /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * 输入 3,7,1（三个数之间打逗号），回车后屏幕输出：
 *  1.00, 3.00, 7.00
 * 过程：S1 中 3>7 不成立不换；S2 中 3>1 成立，把 a、c 互换得 a=1,c=3；S3 中 7>3 成立，把 b、c 互换得 b=3,c=7。
 * 最终 a=1,b=3,c=7，顺序输出即由小到大，与课本运行结果一致。
 *
 * 【运行与演示】点 ▶ 运行后输入 "3,7,1" 回车即可；再试 "9,5,7" 等乱序组合，观察三次 if 各自换不换。
 */

/*
 * 【讲解过程稿】
 *
 * 开场：同学们，上例排两个数我们用了一次"借杯交换"。今天加一个数，排三个。【互动停顿：停 2~3 秒，问"排三个数最少要比较几次？"让学生猜，再揭晓"课本用三次"】
 * 这题在干什么：读入三个数 a、b、c，通过三次"比较+交换"，把最小者赶到 a、次小赶到 b、最大留在 c，然后顺序输出。
 * 大思路：别看代码长，它就是例 4.2 那个"if + 三步交换"的骨架重复三遍，只是每遍比的变量对不同。记住 S1 锁最小、S3 理剩下，就不慌。
 * 逐块讲：
 *   - 第一块定义加读入：四个变量 a、b、c、t，scanf 三个 %f 用逗号分隔。
 *   - 第二块第一个 if(a>b)：把 a、b 里较小的换到 a。
 *   - 第三块第二个 if(a>c)：把 a、c 里较小的换到 a；做完这两步，a 已经是三个里最小的。
 *   - 第四块第三个 if(b>c)：剩下 b、c 谁大还没定，这一步把它们理顺。【此处投屏 li4.3.puml 盒图】
 *   - 最后一行顺序输出 a,b,c，因为已经 a≤b≤c，直接打就是由小到大。
 * 关键转折：全程序的分水岭是第二个 if 做完的那一刻——a 已经锁定为最小者，后面的工作只剩收拾 b 和 c。理解这一点，三次交换就不是死记而是有分工的。
 * 收尾：一句话总结——多次交换的本质是"分步锁定顺序"。留个问题：如果输入的三个数本来就有序，比如 1,2,3，这三个 if 会执行几次交换？【互动停顿：留 3~5 秒，揭晓"一次都不换，原样输出"】
 */

