/*
 * 例 4.10：运输公司对用户计算运输费用。路程越远，运费越低（折扣越大）。标准见课本折扣表：s<250 无折扣；250<=s<500 折扣 2%；500<=s<1000 折扣 5%；1000<=s<2000 折扣 8%；2000<=s<3000 折扣 10%；3000<=s 折扣 15%。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于讲解的中文注释】
 *
 * 题目背景（switch 处理"区间折扣"的技巧：把区间编号成整数 c）：
 * 设每吨每千米货物的基本运费为 p（price），货物重为 w（weight），距离为 s，折扣为 d（discount），则总运费 f（freight）的计算公式为 f = p*w*s*(1-d)。
 * 折扣的"变化点"都是 250 的倍数（250,500,1000,2000,3000）。利用这一特点，在横轴上加一种坐标 c，c 的值为 s/250，代表 250 的倍数；于是"区间"变成"整数 c"，就能用 switch 按 c 分派折扣。
 *
 * 解题思路（对照课本与图 4.16）：
 * ① 读入单价 p、重量 w、距离 s。
 * ② 若 s>=3000，令 c=12（3000km 以上为同一折扣，不让 c 随 s 增大）；否则 c=s/250（整除取整）。
 * ③ switch(c)：c=0→d=0；c=1→d=2；c=2,3→d=5；c=4~7→d=8；c=8~11→d=10；c=12→d=15。
 * ④ 用 f=p*w*s*(1-d/100) 计算总运费，按 %10.2f 输出。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - 解此题的关键是找出折扣 d 与距离 s 的关系；找出"变化点都是 250 倍数"这一规律后，用 c=s/250 把区间映射成整数，switch 就能用。若没什么规律，就不能以这种方式使用 switch，可改用嵌套 if（if…else if…else if…else）处理。
 * - c 和 s 是整型变量，因此 c=s/250 的结果为整数（整除截断）；当 s>=3000 时令 c=12，用一个 case 就可以处理所有 s>=3000 的情况。
 * - 多个 case 共用一组语句再次出现：case 2: 与 case 3: 叠在一起共用 d=5;break;，case 4~7、case 8~11 同理。
 * - 变量名尽量采用"见名知义"原则（price,weight,discount,freight）；本书例题因是练习程序、兼顾多数读者习惯，用首字母或缩写 p,w,d,f。
 * - 第 6 行 printf 提示输入，是为了方便用户、避免出错、形成友好界面；建议在 scanf 前用 printf 输出必要的提示信息。
 *
 * 难点：
 * - 难点是"区间→整数编号"的映射思想：先看出变化点规律，再构造 c=s/250，把连续区间离散化，这是把 switch 用活的关键一步。
 *
 * 易错易混点：
 * - c=s/250 是整除，s=499 时 c=1、s=500 时 c=2，边界要心里有数。
 * - s>=3000 必须先特判 c=12，否则 c 会超过 12、switch 里没有对应 case 就都不执行（d 未赋值）。
 * - d 是折扣百分数（2 代表 2%），代入公式要写 (1-d/100)，别直接写 (1-d)。
 * - scanf 格式 "%f,%f,%d"：p、w 用 %f（float），s 用 %d（int），顺序和类型别错。
 *
 * 内存与编译器原理：
 * - c、s 是 int（整除截断正是本例需要的）；p、w、d、f 是 float。
 * - d/100 中 d 是 float，除 100 得小数比例，不会整除截断；若 d 是 int 写 d/100 就会得 0，是本类题常见坑。
 * - switch 按 c 跳转；连续 case 标号共用语句，正是利用"命中后顺序执行到 break"的特性。
 */

#include <stdio.h>            /* 引入标准输入输出库，提供 printf 和 scanf */

int main()                    /* 主函数 */
{
    int c, s;                 /* c 是距离编号（s/250），s 是距离 km */
    float p, w, d, f;         /* p 单价、w 重量、d 折扣百分数、f 总运费 */

    printf("please enter price,weight,discount:");   /* 提示输入的数据 */
    scanf("%f,%f,%d", &p, &w, &s);   /* 输入单价、重量、距离 */

    if (s >= 3000) c = 12;    /* 3000km 以上为同一折扣，统一编号 12 */
    else c = s / 250;         /* 3000km 以下各段折扣不同，c 的值不相同 */

    switch (c)                /* 按编号 c 分派折扣 d */
    {
        case 0:  d = 0;  break;   /* c=0，代表 250km 以下，折扣 d=0 */
        case 1:  d = 2;  break;   /* c=1，代表 250~500km，折扣 d=2% */
        case 2:                 /* c=2 和 3 共用，代表 500~1000km */
        case 3:  d = 5;  break;   /* 折扣 d=5% */
        case 4:                 /* c=4~7 共用，代表 1000~2000km */
        case 5:
        case 6:
        case 7:  d = 8;  break;   /* 折扣 d=8% */
        case 8:                 /* c=8~11 共用，代表 2000~3000km */
        case 9:
        case 10:
        case 11: d = 10; break;   /* 折扣 d=10% */
        case 12: d = 15; break;   /* c=12，代表 3000km 以上，折扣 d=15% */
    }

    f = p * w * s * (1 - d / 100);   /* 计算总运费 */
    printf("freight=%10.2f\n", f);   /* 输出总运费，取两位小数 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * 输入 100,20,300（单价 100、重量 20、距离 300），回车后屏幕输出：
 * freight= 588000.00
 * 过程：s=300<3000，c=300/250=1，命中 case 1 得 d=2；f=100*20*300*(1-2/100)=600000*0.98=588000。
 * 与课本运行结果一致。
 *
 * 【运行与演示】点 ▶ 运行后输入 "100,20,300" 回车；再试 "100,20,3000"（c=12，d=15）等，观察不同距离档的折扣与运费。
 */

/*
 * 【讲解过程稿】
 *
 * 开场：同学们，前面 switch 都是"一个值对一个分支"。今天这题是"一段距离对一个折扣"——区间怎么喂给 switch？【互动停顿：停 2~3 秒，问"switch 能直接判断 s 在哪个区间吗？"让学生想，再揭晓"不能，得先把区间变成整数"】
 * 这题在干什么：读单价、重量、距离，先把距离 s 折算成编号 c=s/250（3000 以上统一记 12），再 switch(c) 查出折扣 d，最后套公式 f=p*w*s*(1-d/100) 算总运费。
 * 大思路：核心就一招——"区间离散化"。看出折扣变化点都是 250 的倍数，于是用 c=s/250 把连续的距离轴切成一格一格整数，switch 就能按格子分派了。
 * 逐块讲：
 *   - 第一块提示加读入：printf 提示，scanf 读 p、w（%f）和 s（%d）。
 *   - 第二块 if(s>=3000) c=12 else c=s/250：把距离映射成编号，3000 以上特判成 12。
 *   - 第三块 switch(c)：0→0%、1→2%、2,3→5%、4~7→8%、8~11→10%、12→15%；连续 case 叠在一起共用一条赋值。【此处投屏 li4.10.puml 盒图】
 *   - 第四块算 f 并 %10.2f 输出。
 * 关键转折：全程序最要紧的是 c=s/250 这一步映射。没有它，switch 面对连续区间无从下口；有了它，区间题就变成了例 4.6 那种"对号入座"。反过来，若变化点没规律，这招失效，就得退回嵌套 if。
 * 收尾：一句话总结——switch 吃整数，区间先编号。留个问题：如果输入距离 s=3500，c 会是多少、走哪个 case？【互动停顿：留 3~5 秒，揭晓"特判 c=12，走 case 12 得 d=15，不会算成 14"】
 */

