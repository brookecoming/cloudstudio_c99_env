/*
 * 例 4.2：输入两个实数，按由小到大的顺序输出这两个数。
 * 【本例课本直接给出了 C 源码，本文件忠实照搬，只补充便于讲解的中文注释】
 *
 * 题目背景（这是选择结构里第一个"交换"例子）：
 * 例 4.1 是"判断后走两条路"，这一例要解决的是"顺序不对就把它换过来"。
 * 给你两个数 a 和 b，不保证谁大谁小，要求输出时小的在前、大的在后。
 * 思路很直接：如果 a 比 b 大，就把两个变量的值互换一下，换完 a 里自然是小数、b 里是大数，再依次输出即可。
 *
 * 解题思路（对照课本步骤与盒图）：
 * ① 定义两个 float 变量 a、b，再定义一个临时变量 t 用来中转。
 * ② 从键盘读入 a、b 两个数（课本 scanf 用 "%f,%f"，输入时两个数之间要打逗号）。
 * ③ 用 if(a>b) 判断：若成立，借助 t 把 a、b 的值互换；若不成立，什么都不做。
 * ④ 依次输出 a、b，此时 a 是小数、b 是大数，就是由小到大。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - 交换两个变量的值必须借助第三个变量 t，三步走：t=a; a=b; b=t;。
 * - 不能写成 a=b; b=a;，那样做会把 a 原来的值冲掉，两个变量最后变成同一个值，交换失败。
 * - 课本用"两杯水互换要借第三个空杯"来比喻这个三步交换，非常形象。
 * - if 后面跟的是一个用花括号括起来的复合语句（三行交换），因为要连着做好几件事。
 *
 * 难点：
 * - 真正的难点是理解"为什么必须借 t"：赋值是"覆盖"，不是"交换"，直接互相赋值会丢数据。
 *
 * 易错易混点：
 * - 交换三步的顺序不能乱：先 t=a 把 a 存起来，再 a=b，最后 b=t；写成先 a=b 就丢了 a 的原值。
 * - 课本 scanf 格式是 "%f,%f"，两个数之间要有逗号；若改成 "%f%f" 则用空格或回车分隔。
 * - if(a>b) 后面不要加分号，否则交换永远不执行。
 *
 * 内存与编译器原理：
 * - a、b、t 是三个独立的内存格子；交换本质是三次"读一格、写另一格"的搬移，t 是中转格。
 * - float 单精度约 6~7 位有效数字，本例只打印两位小数（%5.2f）足够，也避免暴露浮点误差。
 * - %5.2f 表示总共占 5 列、保留 2 位小数，不足 5 列时左边补空格，所以输出会带前导空格对齐。
 */

#include <stdio.h>            /* 引入标准输入输出库，提供 printf 和 scanf */

int main()                    /* 主函数 */
{
    float a, b, t;            /* a、b 放两个待排序的数，t 是交换用的中转变量 */

    scanf("%f,%f", &a, &b);   /* 读入两个实数，课本格式用逗号分隔，变量前要加 & */

    if (a > b)                /* 判断：a 比 b 大吗？ */
    {                         /* 大于才需要交换，下面三行是一个复合语句 */
        t = a;                /* 先把 a 的值存进中转格 t，防止被覆盖 */
        a = b;                /* 再把 b 的值搬进 a */
        b = t;                /* 最后把 t 里存的原 a 值搬进 b，交换完成 */
    }

    printf("%5.2f,%5.2f\n", a, b);   /* 依次输出 a、b，此时已是由小到大 */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * 输入 3.6,-3.2（两个数之间打逗号，与课本 scanf 的 "%f,%f" 对应），回车后屏幕输出：
 * -3.20, 3.60
 * 因为 a=3.6 比 b=-3.2 大，if 成立，三行交换把小的换到 a、大的换到 b，再依次输出就是由小到大。
 * 与课本运行结果一致。
 *
 * 【运行与演示】点 ▶ 运行后程序停下等输入，输入 "3.6,-3.2" 再回车即可看到交换效果。
 * 再试一组本来就有序的，比如 "1,2"，会发现 if 不成立、一行都不交换，输出原样 1.00, 2.00。
 */

/*
 * 【讲解过程稿】
 *
 * 开场：同学们，上例我们学会"判断后走两条路"。今天这题换个玩法——不走路，改"换位置"。给你两个数，不告诉你谁大谁小，要你输出时小的在前。【互动停顿：停 2~3 秒，问"如果 a 已经比 b 小，还要不要换？"让全班齐答"不用"，再继续】
 * 这题在干什么：读入两个实数 a 和 b，如果 a 比 b 大，就把它俩的值互换，换完依次输出，自然就是由小到大。
 * 大思路：整个程序就一个 if，if 里面三行交换。记住"判断 + 三步交换"这个骨架，后面例 4.3 排三个数就是把这个骨架重复三遍。
 * 逐块讲：
 *   - 第一块是定义和读入：a、b 放两个数，t 是中转；scanf 用 "%f,%f"，所以输入时两个数之间要打逗号。
 *   - 第二块是 if(a>b) 这个闸门：只有 a 真比 b 大才进去换，否则跳过，原样输出。
 *   - 第三块是花括号里三行交换：t=a 先把 a 存住，a=b 把 b 搬进 a，b=t 把存着的原 a 搬进 b。【此处投屏 li4.2.puml 盒图】
 * 关键转折：全程序最要紧的是"为什么必须借 t"。赋值是覆盖不是交换，你写 a=b 的那一瞬间，a 原来的值就没了，再写 b=a 得到的还是 b 自己，等于没换。所以必须先拿 t 把 a 存住。
 * 收尾：一句话总结——交换要借第三个杯子。留个问题：如果把三行写成 a=b; b=a; 会输出什么？【互动停顿：留 3~5 秒，揭晓"两个都变成 b 的原值，交换失败"】
 */

