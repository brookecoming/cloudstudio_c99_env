/*
 * 例 4.8：写一程序，判断某一年是否为闰年。
 * 【本例课本直接给出了 C 源码（程序 1 三层嵌套 if），本文件忠实照搬程序 1，只补充便于讲解的中文注释】
 *
 * 题目背景（标志变量 leap 的第一次使用 + 三层嵌套 if）：
 * 闰年规则：能被 4 整除但不能被 100 整除，或者能被 400 整除的年份是闰年。
 * 课本程序 1 用三层嵌套 if 逐层筛（先 %4、再 %100、再 %400），把结果记进标志变量 leap（1 闰年 / 0 非闰年），最后统一按 leap 输出。
 *
 * 解题思路（对照课本流程图 4.14 与程序 1）：
 * ① 读入年份 year。
 * ② 第一层 if(year%4==0)：不能被 4 整除直接 leap=0。
 * ③ 能被 4 整除再进第二层 if(year%100==0)：不能被 100 整除则 leap=1。
 * ④ 能被 100 整除再进第三层 if(year%400==0)：能则 leap=1，不能则 leap=0。
 * ⑤ 最后 if(leap) 打印 "%d is "，else 打印 "%d is not "，再统一接 "a leap year.\n"。
 *
 * 关键知识点（对应课本"程序分析"）：
 * - leap 是一个"标志变量"：闰年令 leap=1，非闰年令 leap=0，最后检查 leap 决定输出哪句。
 * - 第 21 行 if(leap) 中，若 leap 非 0（如 1）则判断为真；写 if(leap) 与写成 if(leap!=0) 含义相同。
 * - 请仔细分析程序中各层 if 与 else 的配对关系；写程序时采取锯齿形式，可以清楚地看明白嵌套关系（课本建议今后一定要采用锯齿形式）。
 * - 输出拆成两段 printf 是为了让 is / is not 共用后半句 "a leap year.\n"，避免重复写整句。
 *
 * 难点：
 * - 难点是三层嵌套的"筛子"逻辑：每一层 else 的含义要读准（%4 不成立→非闰；%4 成立但 %100 不成立→闰；%100 成立再看 %400）。
 *
 * 易错易混点：
 * - 整除判断用 year%4==0（余数为 0），别写成 year/4==0 或 year%4=0。
 * - 三层 if 的 else 各跟最近的 if，缩进错了肉眼就会配错；务必锯齿形书写。
 * - 2100 能被 4 和 100 整除但不能被 400 整除，是非闰年；2000 能被 400 整除是闰年——这两个是经典反例。
 *
 * 内存与编译器原理：
 * - year、leap 是两个 int 格子；leap 只存 0/1，充当"布尔标志"，C99 前没有 bool 类型就用 int 当标志。
 * - % 是取余运算符，year%4 求余数；三次取余 + 三次比较构成全部判断，无循环、开销极小。
 * - if(leap) 编译后就是"测试 leap 是否非零"，与 if(leap!=0) 生成同样的条件跳转。
 */

#include <stdio.h>            /* 引入标准输入输出库，提供 printf 和 scanf */

int main()                    /* 主函数 */
{
    int year, leap;           /* year 放年份，leap 是闰年标志（1 闰 / 0 非闰） */

    printf("enter year:");    /* 打印提示，不换行 */
    scanf("%d", &year);       /* 读入年份，变量前要加 & */

    if (year % 4 == 0)        /* 第一层：能被 4 整除吗 */
    {
        if (year % 100 == 0)  /* 第二层：能被 100 整除吗 */
        {
            if (year % 400 == 0)   /* 第三层：能被 400 整除吗 */
                leap = 1;     /* 能：闰年 */
            else
                leap = 0;     /* 不能：非闰年 */
        }
        else
            leap = 1;         /* 能被 4 整除但不能被 100 整除：闰年 */
    }
    else
        leap = 0;             /* 不能被 4 整除：非闰年 */

    if (leap)                 /* 按标志变量决定前半句（if(leap) 等价 if(leap!=0)） */
        printf("%d is ", year);
    else
        printf("%d is not ", year);
    printf("a leap year.\n"); /* 后半句共用，拼成完整一句 */

    return 0;                 /* 程序正常结束 */
}

