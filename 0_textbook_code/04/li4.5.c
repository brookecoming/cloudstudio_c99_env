/*
 * 例 4.5：有一阶跃函数 y = -1 (x<0)；y = 0 (x=0)；y = 1 (x>0)。编一程序，输入一个 x 值，要求输出相应的 y 值。
 * 【本例课本直接给出了 C 源码（程序 1 / 程序 2 两种写法），本文件忠实照搬程序 1，只补充便于讲解的中文注释】
 *
 * 题目背景（if 嵌套的第一个实战）：
 * y 的可能值不是两个而是三个，因此不可能只用一个简单的（无内嵌 if 的）if 语句来实现。
 * 课本给出两种方法：先后用 3 个独立的 if 语句处理，或用一个嵌套的 if 语句处理；本文件采用课本推荐的嵌套写法（程序 1）。
 *
 * 解题思路（对照课本方法 2 与流程图 4.12）：
 * ① 输入 x。
 * ② 若 x<0，则 y=-1；否则（即 x>=0）再判：若 x==0，则 y=0；否则（即 x>0）y=1。
 * ③ 输出 y。
 * 嵌套的关键是把内层的 if—else 放在外层的 else 子句中，靠外层 else 相隔，内层 else 就不会误和外层 if 配对。
 *
 * 关键知识点（对应课本"程序分析/注意"）：
 * - 嵌套 if 中 else 总是与它上面的最近的未配对的 if 配对；程序 1 把内嵌 if 放进外层 else 里，配对关系清晰不会搞混。
 * - 如果 if 与 else 的数目不一样，为实现设计者的意图，可以加花括号来确定配对关系。
 * - 写程序时对选择结构和循环结构应采用锯齿形的缩进，使程序清晰、易读（课本"注意"）。
 * - 三段赋值 y=-1 / y=0 / y=1 恰好覆盖 x<0、x=0、x>0 三种互斥情况，必居其一。
 *
 * 难点：
 * - 难点是看清"else 里再套一个 if—else"的层次：外层 else 代表"x>=0"这半边，内层再把它切成 x==0 和 x>0。
 *
 * 易错易混点：
 * - 判相等用 x==0（两个等号），写成 x=0 就变成赋值、条件恒真，逻辑全错。
 * - 程序 2 那种 if(x>=0) 里再 if(x>0)…else… 的写法，else 跟的是内层 if，初学者极易配错；本文件用程序 1 规避。
 * - scanf 读 int 用 %d，变量前要加 &。
 *
 * 内存与编译器原理：
 * - x、y 是两个 int 格子；三次比较只有一条路径会被执行，其余分支跳过，所以最终 y 只被赋值一次。
 * - 嵌套 if 编译后是一串"比较 + 条件跳转"，层次越深跳转越多，但本例只有两层，开销可忽略。
 * - 输出用 %d 打整数，x 和 y 一起打便于核对输入落在哪一段。
 */

#include <stdio.h>            /* 引入标准输入输出库，提供 printf 和 scanf */

int main()                    /* 主函数 */
{
    int x, y;                 /* x 放输入的自变量，y 放对应的函数值 */

    scanf("%d", &x);          /* 读入一个整数 x，变量前要加 & */

    if (x < 0)                /* 第一段：x 小于 0 */
        y = -1;               /* 则 y = -1 */
    else                      /* 否则 x >= 0，进入内层再细分 */
        if (x == 0) y = 0;    /* 内层：x 等于 0 则 y = 0 */
        else y = 1;           /* 内层：剩下即 x > 0，则 y = 1 */

    printf("x=%d,y=%d\n", x, y);   /* 输出 x 和对应的 y */
    return 0;                 /* 程序正常结束 */
}

/*
 * 运行结果（本机 CLion / MinGW-GCC 实测）：
 * 输入 -5，回车后屏幕输出：
 * x=-5,y=-1
 * 因为 -5<0 走第一分支 y=-1。再试 0 得 x=0,y=0；试 5 得 x=5,y=1，三段都覆盖到。
 * 与课本程序 1 运行结果一致。
 *
 * 【运行与演示】点 ▶ 运行后分别输入 -5、0、5 各跑一次，观察 y 在 -1/0/1 之间跳变，阶跃函数就直观了。
 */

/*
 * 【讲解过程稿】
 *
 * 开场：同学们，前面 if 都只有一层。今天这题 y 有三个可能值，一层 if 装不下，得"套娃"。【互动停顿：停 2~3 秒，问"y 有几种取值？"让全班齐答"三种"，再继续】
 * 这题在干什么：输入一个 x，按 x<0、x=0、x>0 三段分别给 y 赋 -1、0、1，再输出。
 * 大思路：把它看成"先切一刀、再切一刀"。外层 if 先把 x<0 切出去；剩下的 x>=0 这半边，交给外层 else 里的内层 if 再切成 x=0 和 x>0。两刀下去三段齐了。
 * 逐块讲：
 *   - 第一块定义加读入：int x,y，scanf 用 %d。
 *   - 第二块外层 if(x<0)：成立就 y=-1，一句话完事。
 *   - 第三块外层 else 里套的内层 if(x==0)…else…：把 x>=0 这半边再细分成 y=0 和 y=1。【此处投屏 li4.5.puml 盒图】
 *   - 最后一行 printf 把 x 和 y 一起打出来核对。
 * 关键转折：全程序最要紧的是"内层 if 必须放在外层 else 里面"。因为 else 配对认"最近未配对的 if"，你把内层 if 摆错位置，else 就会跟错对象，三段就乱了。课本程序 2 就是故意摆另一种位置让你对比配对关系的。
 * 收尾：一句话总结——多段判断靠嵌套，配对靠"最近未配对"规则。留个问题：输入 0 的时候，程序走的是外层 if 还是外层 else？【互动停顿：留 3~5 秒，揭晓"走外层 else，再进内层 if(x==0)"】
 */

